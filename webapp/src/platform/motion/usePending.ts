import { useEffect, useRef, useState } from "react"

/**
 * Показывать ли скелетон.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Два числа, и оба лечат противоположные болезни.
 *
 * **Задержка 150 мс.** Ответ, пришедший за сотню миллисекунд, не должен
 * мигать скелетоном: вспышка серых плашек на десятую долю секунды читается
 * как сбой отрисовки, а не как загрузка. Поэтому первые 150 мс ожидания
 * на экране не меняется ничего.
 *
 * **Удержание 400 мс.** Если скелетон всё-таки показали, он обязан постоять.
 * Скелетон, мелькнувший на 30 мс, — это тот же мигающий кадр, только с другой
 * стороны. Ответ, пришедший через 160 мс, ждёт до 550-й.
 *
 * Оба числа из DESIGN.md, раздел «Скелетоны, не спиннеры». Своих здесь нет.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * **Пока данные лежат в браузере, ждать нечего, и это честно.** Хук написан
 * не впрок: он включится в ту минуту, когда за выдачей появится сервер, и
 * включится один раз на весь кабинет, а не двадцатью самодельными таймерами
 * по экранам. Заводить его вместе с сервером было бы поздно: тогда правила
 * 150 и 400 разъехались бы по местам применения.
 */
function usePending(active: boolean): boolean {
  const [shown, setShown] = useState(false)
  const shownSince = useRef(0)

  useEffect(() => {
    if (active) {
      const timer = window.setTimeout(() => {
        shownSince.current = performance.now()
        setShown(true)
      }, 150)
      return () => window.clearTimeout(timer)
    }

    if (!shown) return

    const held = performance.now() - shownSince.current
    const rest = Math.max(0, 400 - held)
    const timer = window.setTimeout(() => setShown(false), rest)
    return () => window.clearTimeout(timer)
  }, [active, shown])

  return shown
}

export { usePending }
