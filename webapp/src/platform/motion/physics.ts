import type { Transition, Variants } from "motion/react"

/**
 * Физика движения кабинета — одна на весь продукт.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ЧТО ИЗМЕНИЛОСЬ И ПОЧЕМУ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Спека движения писалась скупо: 120–200 мс, только прозрачность и сдвиг,
 * ни отскока, ни пружин. Это давало продукт, который **ничего не делает
 * неправильно и при этом ощущается мёртвым**: цвета менялись, блоки гасли
 * и загорались, но ни у чего не было веса. Владелец сказал прямо: «анимации
 * странные, карточка объекта вообще не анимирована».
 *
 * Запреты сняты решением владельца. Осталось одно правило, и оно не про вкус:
 * системная настройка «меньше движения» уважается. Для части людей движение
 * вызывает тошноту, и это не то, о чём договариваются.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ПОЧЕМУ ПРУЖИНЫ, А НЕ ДЛИТЕЛЬНОСТИ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Кривая с длительностью останавливается ровно в срок — и именно поэтому
 * читается как механизм: настоящие предметы доезжают, а не выключаются.
 * Пружина ещё и **прерываема**: если человек нажал второй раз, пока первая
 * не доиграла, движение продолжится с текущей скорости, а не дёрнется
 * с начала. На тридцати-пятидесяти касаниях за смену это заметно.
 *
 * Числа заданы через `visualDuration` и `bounce`, а не через жёсткость
 * с затуханием: первое — сколько это ощущается по времени, второе — сколько
 * в этом жизни. Пересчитывать stiffness в уме не приходится никому.
 */

/**
 * Отклик под пальцем.
 *
 * Самая быстрая пружина продукта: нажатие обязано случиться раньше, чем
 * человек успел усомниться. Отскок почти нулевой — кнопка, которая
 * пружинит обратно, читается как игрушка, а здесь ею списывают деньги.
 */
const PRESS: Transition = { type: "spring", visualDuration: 0.14, bounce: 0 }

/**
 * Появление блока внутри экрана.
 *
 * Основная пружина кабинета. Отскок 0.18 — на глаз это «доехало и осело»,
 * а не «прилетело и качнулось».
 */
const ENTER: Transition = { type: "spring", visualDuration: 0.34, bounce: 0.18 }

/**
 * Окно, лист, панель.
 *
 * Решительнее появления блока: окно перекрывает работу, и мешкать ему нельзя.
 */
const OVERLAY: Transition = { type: "spring", visualDuration: 0.26, bounce: 0.12 }

/**
 * Общий элемент, который переезжает между экранами.
 *
 * Медленнее всех остальных намеренно: это единственное движение продукта,
 * за которым глаз обязан проследить. Слишком быстрый переезд не связывает
 * строку выдачи с карточкой, а просто мигает.
 */
const SHARED: Transition = { type: "spring", visualDuration: 0.42, bounce: 0.1 }

const SPRING = { press: PRESS, enter: ENTER, overlay: OVERLAY, shared: SHARED } as const

/**
 * Шаг каскада, в секундах.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Каскад по спискам спека запрещала, и запрет был не пустой: тридцать строк,
 * загорающихся по очереди, агент видит по сто раз за смену. Владелец запрет
 * снял, но арифметика никуда не делась, поэтому каскад **ограничен сверху**
 * (см. `stepOf`): первые полтора десятка идут волной, остальные приезжают
 * вместе с последним из них.
 *
 * `row` мельче `block` втрое: у строки задача — показать, что список
 * пересобрался, а не представить каждый объект по отдельности.
 */
const STAGGER = { row: 0.018, block: 0.055 } as const

/**
 * Сколько элементов участвуют в каскаде.
 *
 * Пятьдесят строк по 18 мс — это 0,9 секунды, за которые ничего не происходит.
 * Четырнадцать — 0,25: волна читается, ожидания нет.
 */
const STAGGER_CAP = 14

/** Задержка элемента по его номеру. Дальше потолка — общая с последним. */
function stepOf(index: number, step: number = STAGGER.row): number {
  return Math.min(index, STAGGER_CAP) * step
}

/**
 * Появление блока: снизу вверх на 14 px.
 *
 * Четырнадцать, а не двадцать шесть, как на лендинге: лендинг человек
 * пролистывает раз, а карточку объекта открывает сорок раз за смену.
 */
const RISE: Variants = {
  hidden: { opacity: 0, y: 14 },
  shown: { opacity: 1, y: 0, transition: ENTER },
}

/** То же, но вбок — для колонок, которые приходят справа. */
const SLIDE: Variants = {
  hidden: { opacity: 0, x: 16 },
  shown: { opacity: 1, x: 0, transition: ENTER },
}

/**
 * Появление с приближением.
 *
 * Только для медиа и того, что человек воспринимает как предмет: кадр
 * объекта, обложка подборки. Текст масштабировать нельзя — он при этом
 * заметно мылится.
 */
const ZOOM: Variants = {
  hidden: { opacity: 0, scale: 0.97 },
  shown: { opacity: 1, scale: 1, transition: ENTER },
}

/**
 * Контейнер каскада.
 *
 * `delayChildren` держит паузу до первого ребёнка: без неё каскад стартует
 * одновременно с появлением самого контейнера и первые два блока сливаются.
 */
function group(step: number = STAGGER.block, delay = 0.04): Variants {
  return {
    hidden: {},
    shown: { transition: { staggerChildren: step, delayChildren: delay } },
  }
}

export { SPRING, STAGGER, STAGGER_CAP, stepOf, RISE, SLIDE, ZOOM, group }
