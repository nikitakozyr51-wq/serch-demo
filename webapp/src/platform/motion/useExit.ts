import { useEffect, useState } from "react"

/**
 * Держать узел на экране, пока он исчезает.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ХУК, ЕСЛИ ПОЯВЛЕНИЕ ОБОШЛОСЬ ОДНИМ КЛАССОМ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Появление на CSS собирается само: узел встал в дерево — анимация пошла.
 * С исчезновением так не выходит. `{open ? <Окно/> : null}` убирает узел
 * из дерева в том же кадре, в котором `open` стал ложью, и анимировать
 * уже нечего: элемента нет.
 *
 * Поэтому решение принимает не стиль, а состояние. Хук помнит, что окно
 * было открыто, и оставляет его на экране ещё 260 мс — ровно на время
 * ухода, — помечая эти 260 мс словом `leaving`.
 *
 * **В кабинете не исчезало ничто**, и это была самая заметная дыра в движении:
 * шесть окон, колонка фильтров и полка сообщений пропадали за один кадр.
 * Исчезновение видно лучше появления — человек уже смотрит именно туда,
 * потому что сам туда себя и привёл нажатием.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Библиотеки здесь нет намеренно. `AnimatePresence` из `framer-motion` делает
 * то же самое, но тянет за собой вторую систему движения рядом с уже
 * написанной на CSS — и пружины, которые в кабинете запрещены решением
 * владельца. Двадцать строк против тридцати килобайт.
 */

/**
 * Отключено ли движение в системе.
 *
 * Читается в момент закрытия, а не при первом показе: человек мог включить
 * настройку, пока окно было открыто.
 */
function reducedMotion(): boolean {
  return window.matchMedia("(prefers-reduced-motion: reduce)").matches
}

/**
 * 260 мс — роль «Окно» из `docs/MOTION.md`, приход и уход одним числом.
 *
 * Число обязано совпадать с длительностью `.motion-out` в `index.css`: узел,
 * снятый раньше конца анимации, обрывает её на середине, то есть исчезает
 * рывком — ровно ради устранения которого всё и делается.
 *
 * Раньше здесь стояло 120 против 200 у прихода, и окно уходило вдвое быстрее,
 * чем приезжало. Колонка фильтров показывала это нагляднее всего: затемнение
 * гасло за 120 мс, а панель ехала 200, и последние восемь сотых она уезжала
 * по уже светлому экрану — владелец назвал это «уход фильтра выглядит странно».
 */
const WINDOW_MS = 260

function useExit(open: boolean, durationMs = WINDOW_MS): { mounted: boolean; leaving: boolean } {
  /**
   * Состояние заведено ТОЛЬКО ради ухода, и это важно для скорости.
   *
   * Появление ничего не ждёт: `mounted` считается прямо из `open`, без второго
   * прохода отрисовки. Раньше здесь стоял эффект, который после открытия
   * дописывал состояние, — то есть каждое открытие окна стоило лишней
   * перерисовки всего поддерева. Палитру открывают десятки раз за смену.
   *
   * Переход `open` отслеживается сравнением с прошлым значением прямо
   * в отрисовке — это тот самый случай, для которого React такое и разрешает:
   * состояние подстраивается под изменившийся проп, а не следует за ним
   * с задержкой в кадр.
   */
  const [exiting, setExiting] = useState(false)
  const [wasOpen, setWasOpen] = useState(open)

  if (wasOpen !== open) {
    setWasOpen(open)
    // Закрылось — начинается уход. Открылось — уход отменяется: окно, которое
    // успели открыть обратно, обязано остаться, а не доиграть исчезновение.
    // При отключённом движении ухода нет вовсе: ждать 260 мс невидимой
    // анимации — задержка без причины, а не бережность.
    setExiting(!open && !reducedMotion())
  }

  useEffect(() => {
    if (!exiting) return
    const timer = window.setTimeout(() => setExiting(false), durationMs)
    return () => window.clearTimeout(timer)
  }, [exiting, durationMs])

  return { mounted: open || exiting, leaving: exiting }
}

/**
 * То же самое, но для окна, которому нужно ЧТО показывать.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Окно подборки знает адрес объекта, окно руководителя — какое из четырёх
 * оно. Обе величины лежат в том же состоянии, которое означает «открыто»:
 * адрес есть — окно открыто, адреса нет — закрыто. И в момент закрытия
 * значение уже пусто, а рисовать уход надо ещё 260 мс.
 *
 * Поэтому последнее непустое значение придерживается здесь, а не ссылкой
 * на месте применения: ссылку нельзя читать во время отрисовки, а два таких
 * места в кабинете уже есть — выдача и настройки агентства.
 */
function useExitValue<T>(
  value: T | null,
  durationMs = WINDOW_MS,
): { mounted: boolean; leaving: boolean; value: T | null } {
  const { mounted, leaving } = useExit(value !== null, durationMs)
  const [shown, setShown] = useState(value)

  // Подстройка состояния под изменившийся проп прямо в отрисовке — тот же
  // приём, что и выше: значение обязано быть готово к первому же кадру.
  if (value !== null && value !== shown) setShown(value)

  return { mounted, leaving, value: shown }
}

export { useExit, useExitValue }
