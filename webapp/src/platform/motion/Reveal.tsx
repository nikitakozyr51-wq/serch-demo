import { motion } from "motion/react"
import type { ReactNode } from "react"

import { cn } from "@/lib/utils"
import { RISE, SLIDE, ZOOM, group } from "./physics"

/**
 * Два кирпича, из которых собирается появление любого экрана кабинета.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * `Stagger` — контейнер, который раздаёт детям очередь.
 * `Reveal` — сам блок, который приезжает.
 *
 * Заведены компонентами, а не набором пропсов на каждом экране, ровно по той
 * же причине, по какой в продукте одна кнопка на все нажатия: иначе через
 * месяц на четырёх экранах будет четыре разных «появления», и ни одно
 * не будет тем, которое утверждали.
 *
 * **Движение навешивается снаружи, а не внутрь готовых блоков.** Карточка
 * объекта собрана из закрытых частей (`CardMedia`, `CardHeading`), и лезть
 * внутрь каждой значило бы разбирать их ради анимации. Обёртка решает ту же
 * задачу и ничего не ломает.
 */

/** Как именно блок приезжает. По умолчанию — снизу. */
type Motion = "rise" | "slide" | "zoom"

const VARIANTS = { rise: RISE, slide: SLIDE, zoom: ZOOM } as const

function Reveal({
  children,
  as = "rise",
  className,
}: {
  children: ReactNode
  as?: Motion
  className?: string
}) {
  return (
    <motion.div variants={VARIANTS[as]} className={cn("min-w-0", className)}>
      {/* Через фрагмент, а не напрямую: правило типографики запрещает голый
          текст в разметке, а `children` для него неотличим от текста. Так же
          обёрнуто содержимое колонок в карточке объекта. */}
      <>{children}</>
    </motion.div>
  )
}

/**
 * Контейнер каскада.
 *
 * `initial`/`animate` объявлены здесь, а не на детях: очередь раздаёт родитель,
 * и дети обязаны стартовать по его команде, а не каждый по своей.
 *
 * Ключ пробрасывается снаружи там, где каскад должен переиграться, — например
 * при переходе к следующему объекту стрелкой. Без ключа React переиспользует
 * узлы, и новый объект въезжает в чужую, уже доигранную анимацию.
 */
function Stagger({
  children,
  step,
  delay,
  className,
}: {
  children: ReactNode
  /** Шаг очереди в секундах. По умолчанию шаг блока. */
  step?: number
  /** Пауза до первого ребёнка. */
  delay?: number
  className?: string
}) {
  return (
    <motion.div
      variants={group(step, delay)}
      initial="hidden"
      animate="shown"
      className={cn("min-w-0", className)}
    >
      {/* Через фрагмент, а не напрямую: правило типографики запрещает голый
          текст в разметке, а `children` для него неотличим от текста. Так же
          обёрнуто содержимое колонок в карточке объекта. */}
      <>{children}</>
    </motion.div>
  )
}

export { Reveal, Stagger }
