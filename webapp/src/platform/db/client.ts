import { createClient, type SupabaseClient } from "@supabase/supabase-js"

/**
 * Подключение к базе.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ДВА АДРЕСА, ОДИН ПРОДУКТ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Продукт живёт в двух местах, и они устроены по-разному:
 *
 * - **демонстрация на GitHub Pages** — статические файлы, сервера за ними
 *   нет и быть не может. Работа агентства лежит в браузере;
 *   - **рабочая версия** — за ней стоит Supabase, и работа лежит в базе.
 *
 * Различие решается ОДНИМ вопросом: заданы ли адрес и ключ. Заданы — работаем
 * с базой; нет — с браузером. Ни одного `if` про «демо» в экранах при этом
 * не появляется: экраны не знают, откуда пришли данные, и знать не должны.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ПРО КЛЮЧ, КОТОРЫЙ ВИДЕН ВСЕМ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * `anon key` уезжает в браузер и виден любому, кто откроет исходники
 * страницы. **Это не утечка.** Ключ говорит «я это приложение», а не
 * «я такой-то человек»: кто пришёл — решает сеанс входа, а что ему можно —
 * правила доступа в самой базе (RLS, см. миграцию `20260807122001_workspace`).
 *
 * Настоящий секрет — `service_role key` — в браузер не попадает никогда
 * и в этом файле не упоминается вовсе.
 */

const url = import.meta.env.VITE_SUPABASE_URL as string | undefined
const anonKey = import.meta.env.VITE_SUPABASE_ANON_KEY as string | undefined

/**
 * Настроена ли база.
 *
 * Проверяются обе строки: одна без другой — это наполовину настроенное
 * подключение, которое падает на первом же запросе. Лучше честно работать
 * из браузера, чем сломаться на входе.
 */
function hasDatabase(): boolean {
  return typeof url === "string" && url !== "" && typeof anonKey === "string" && anonKey !== ""
}

let client: SupabaseClient | null = null

/**
 * Клиент базы или `null`, если база не настроена.
 *
 * Создаётся один раз и лениво: `createClient` открывает соединение и вешает
 * слушателей на хранилище, и делать это на каждый запрос — значит держать
 * их десятками.
 */
function db(): SupabaseClient | null {
  if (!hasDatabase()) return null
  client ??= createClient(url!, anonKey!, {
    auth: {
      // Сеанс переживает перезагрузку и продлевается сам: агент работает
      // смену целиком, и просить его войти в середине дня нельзя.
      persistSession: true,
      autoRefreshToken: true,
      // Ключ входа в адресе не ищем: продукт не пользуется входом по ссылке,
      // а разбор адреса ломает возвраты `?at=…` с карточки объекта.
      detectSessionInUrl: false,
    },
  })
  return client
}

export { db, hasDatabase }
