import { useEffect } from "react"

import { Typography } from "@/components/typography"
import { isStaleChunk, reloadOnce } from "./chunk-reload"

/**
 * Что видно между экранами и что видно, когда экран не доехал.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ОТКУДА ВЗЯЛСЯ 404 НА ПЕРЕХОДЕ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Каждый экран кабинета грузится отдельным куском кода — `lazyRouteComponent`.
 * Это правильно: иначе первый вход тянул бы восемьдесят экранов разом. Но
 * у такой загрузки два состояния, и оба до сих пор не были нарисованы.
 *
 * **Пока кусок едет** маршрутизатор не показывал ничего. На быстром интернете
 * это незаметно, на медленном — пустой белый экран, и человек не понимает,
 * нажалось ли вообще.
 *
 * **Когда кусок не доехал** — а это происходит буквально каждый раз, когда
 * демонстрацию выложили заново, пока вкладка была открыта, — браузер просит
 * файл со старым именем, GitHub Pages его не находит и отдаёт `404.html`.
 * То есть в ответ на просьбу дать код приходит HTML страницы «не найдено».
 * Браузер пытается выполнить его как код, спотыкается, и на экране вместо
 * раздела оказывается ошибка. Владелец описал это точно: «при переключении
 * некоторых экранов вылетает 404, а не анимация загрузки».
 *
 * Чинится это не ловлей ошибки, а перезагрузкой: старого куска больше нет
 * и не будет, а новый лежит по новому имени в свежем `index.html`. Один
 * перезаход возвращает вкладку к выложенной версии.
 */

/**
 * Экран едет.
 *
 * Ни спиннера, ни прогресса: и то и другое обещает время, которого никто
 * не знает. Вместо этого пульсирует та же плашка `line-1`, что во всех
 * скелетонах кабинета, — язык ожидания в продукте один.
 *
 * Показывается не сразу: у маршрутизатора выставлена задержка, и на быстрой
 * загрузке этот экран не успевает появиться. Мелькание «загружаю» на
 * стомиллисекундном переходе раздражает сильнее, чем сам переход.
 */
function RoutePending() {
  return (
    <div
      data-slot="route-pending"
      role="status"
      aria-live="polite"
      className="flex min-h-0 w-full flex-1 flex-col gap-3 p-6"
    >
      <span className="sr-only">
        <Typography variant="srOnly" tone="dense">
          Экран загружается
        </Typography>
      </span>
      {[0, 1, 2, 3, 4, 5].map((index) => (
        <span
          key={index}
          aria-hidden
          className="skeleton-plate h-row-obj w-full shrink-0 rounded-2xl"
        />
      ))}
    </div>
  )
}

/**
 * Куска нет: страница перезагружается сама, один раз.
 *
 * Признак именно этой беды — сообщение браузера про динамический импорт.
 * Всё остальное (ошибка внутри самого экрана) перезагрузкой не лечится
 * и остаётся на экране честным сообщением: бесконечный цикл «упал —
 * перезагрузился — упал» хуже любой ошибки, потому что не даёт себя прочесть.
 *
 * Сама отметка и признак живут в `chunk-reload.ts` — там же, где объяснение,
 * почему они в `sessionStorage`.
 */
function RouteError({ error }: { error: Error }) {
  const stale = isStaleChunk(error)

  useEffect(() => {
    if (stale) reloadOnce()
  }, [stale])

  return (
    <div
      data-slot="route-error"
      className="flex min-h-0 w-full flex-1 flex-col items-center justify-center gap-4 p-6"
    >
      <Typography variant="panelTitle" tone="default" align="center" as="h1">
        {stale ? "Обновляем страницу" : "Экран не открылся"}
      </Typography>
      <Typography variant="uiText" tone="secondary" align="center">
        {stale
          ? "Демонстрацию выложили заново, пока вкладка была открыта. Забираем свежую версию — это займёт секунду."
          : "Что-то пошло не так при открытии раздела. Попробуйте обновить страницу; если повторится, скажите — посмотрим, что случилось."}
      </Typography>
    </div>
  )
}

export { RouteError, RoutePending }
