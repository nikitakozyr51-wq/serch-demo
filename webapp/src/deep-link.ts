/**
 * Возврат по глубокой ссылке — **до** всего остального.
 *
 * Кабинет это одностраничное приложение: на диске лежит один `index.html`,
 * а все адреса рисует браузер. Статический хостинг об этом не знает и на
 * `/app/search` честно отдаёт «страницы нет». Та страница возвращает человека
 * в кабинет, приложив адрес параметром `?p=`, и здесь адрес забирается обратно
 * в строку браузера.
 *
 * **Почему отдельным файлом, а не строчкой в `main.tsx`.** В JavaScript
 * импорты выполняются раньше любого кода модуля. Маршрутизатор создаётся
 * при импорте `./routes`, и он смотрит на адрес в момент создания. Пока эта
 * правка лежала внутри `main.tsx` под импортами, порядок был такой:
 *
 *   1. импортируется App → routes → маршрутизатор запоминает `/app/?p=/register`,
 *      то есть корень;
 *   2. и только потом строка браузера меняется на `/app/register`.
 *
 * Адрес в строке был правильный, а на экране оставался корень — и человек,
 * пришедший по ссылке на регистрацию, видел не её. Ловилось только на
 * собранной версии: в разработке сервер отдаёт любой путь сам, и подмены
 * не происходит вовсе.
 *
 * Теперь это отдельный модуль, и `main.tsx` импортирует его первым — раньше
 * всего, что умеет читать адрес.
 *
 * `replaceState`, а не переход: технической ссылки с параметром не должно
 * остаться в истории, иначе кнопка «назад» вернёт человека на неё же.
 */

const params = new URLSearchParams(window.location.search)
const target = params.get('p')

if (target) {
  const base = import.meta.env.BASE_URL.replace(/\/+$/, '')
  window.history.replaceState(null, '', base + target)
}

export {}
