import { useNavigate } from "@tanstack/react-router"
import { useState } from "react"

import { Button } from "@/components/controls/Button"
import { Checkbox } from "@/components/controls/Checkbox"
import { Typography } from "@/components/typography"
import { AuthField, AuthShell, useSession, useSessionActions } from "@/features/auth"

/**
 * Оставшиеся экраны входа.
 *
 * Снято с `pIdgz`, `iziCH`, `INCeL`, `RfL9b`. Каркас общий с первыми пятью:
 * форма 920 и тёплая панель 520.
 *
 * **Каждый из четырёх — тупик по своей причине, и ни один не бросает человека.**
 * Код не пришёл — есть «отправить ещё раз». Письмо не пришло — сказано, куда
 * смотреть. Приглашение не ваше — есть «отклонить». Доступ закрыт — есть кому
 * написать и чем стереть свои данные. Мёртвых концов не бывает: у любого
 * состояния есть следующее действие.
 *
 * **Ни одной чужой почты, фамилии и вывески здесь нет.** Раньше стояли: письмо
 * ушло «на i.smirnova@nevsky.ru», приглашение выписано «Королёву Дмитрию»
 * в «Невский проспект», доступ закрыт «2 августа». Это были образцы текста
 * из макета, а не данные, и живой человек читал их как правду о себе. Всё,
 * что известно, теперь берётся из сеанса; чего сеанс не знает — названо
 * общими словами, а не выдумано похоже на настоящее.
 */

/**
 * Пара «вопрос — действие» под кнопкой.
 *
 * **Нажимаемым здесь бывает не всё, и это видно по коду.** «Отправить ещё раз»
 * и «Отклонить» — действия: у них нет своего экрана, за ними стоит письмо
 * и отзыв приглашения, поэтому они названы через `data-action` и ничего
 * не рисуют. «Проверьте папку «Спам»» — не действие, а совет: нажимать в нём
 * нечего, и кнопкой он быть не должен. Кнопка, которая ничего не делает,
 * врёт человеку ровно один раз — в тот момент, когда он её нажал.
 */
function AuthAside({
  question,
  action,
  /** Что произойдёт по нажатию. Не задано — это подпись, а не действие. */
  dataAction,
}: {
  question: string
  action: string
  dataAction?: string
}) {
  return (
    <span className="flex items-center gap-1.5">
      <Typography variant="denseText" tone="dense">
        {question}
      </Typography>
      {dataAction === undefined ? (
        <Typography variant="numericDense" tone="default">
          {action}
        </Typography>
      ) : (
        <button
          type="button"
          data-action={dataAction}
          className="cursor-pointer bg-transparent outline-none focus-visible:outline-solid focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-fg"
        >
          <Typography variant="numericDense" tone="default">
            {action}
          </Typography>
        </button>
      )}
    </span>
  )
}

/**
 * Код подтверждения.
 *
 * **Поле обычное, а не четыре ячейки под цифры.** Так в файле, и это к лучшему:
 * ячейки ломают вставку кода из буфера, а именно так его и вводят чаще всего —
 * скопировав из письма.
 */
export function ConfirmCodePage() {
  const navigate = useNavigate()
  const session = useSession()
  const [code, setCode] = useState("")

  /**
   * Адрес, на который ушёл код, — это почта вошедшего, и другой тут быть
   * не может.
   *
   * Экран открыт всем, и человек мог прийти сюда по ссылке из письма
   * на чужом компьютере, где сеанса нет. Тогда адреса взять неоткуда,
   * и сказано общими словами. Подставить сюда конкретную почту — значит
   * назвать человеку чужой почтовый ящик и отправить его искать письмо
   * там, где его нет.
   */
  const mailbox = session?.email || "вашу рабочую почту"

  /**
   * Код не проверяется, и подтверждение открывает кабинет.
   *
   * За экраном нет сервера — проверять четыре цифры было бы имитацией защиты,
   * которой нет. Зато сам шаг настоящий: человек вводит код, попадает
   * в «Сегодня» и дальше работает под своим сеансом, а не смотрит картинку.
   *
   * Сеанс сюда приходит уже заведённым — код подтверждает почту, а не создаёт
   * агентство. Без сеанса подтверждать нечего: раньше кнопка входила по
   * зашитой чужой почте, то есть открывала кабинет тому, кто в него не
   * заходил. Теперь она ведёт на вход — это и есть недостающий шаг.
   */
  const confirm = () => {
    if (session) {
      void navigate({ to: "/today" })
      return
    }
    void navigate({ to: "/login", search: { returnTo: undefined } })
  }

  return (
    <AuthShell
      title="Введите код из письма"
      subtitle={`Отправили четыре цифры на ${mailbox}. Код живёт десять минут, повторная отправка через шестьдесят секунд.`}
      stepsLabel="ПОЧЕМУ МЫ СПРАШИВАЕМ КОД"
    >
      <div className="flex w-160 flex-col gap-5">
        <AuthField
          label="КОД ИЗ ПИСЬМА"
          value={code}
          onChange={setCode}
          name="code"
          autoComplete="one-time-code"
          placeholderText="Введите четыре цифры"
          hint="вход с нового устройства подтверждается кодом"
        />
      </div>

      <div className="h-7" />

      <div className="flex items-center gap-5">
        <Button variant="primary" size="lg" onClick={confirm}>
          Подтвердить вход
        </Button>
        <AuthAside
          question="Письмо не пришло?"
          action="Отправить ещё раз"
          dataAction="код отправлен ещё раз"
        />
      </div>
    </AuthShell>
  )
}

/**
 * Проверьте почту.
 *
 * Полей нет вовсе — человеку нечего вводить, он ждёт письма. Поэтому кнопка
 * **вторичная**: главное действие сейчас не на экране, а в почтовом ящике,
 * и графитовая кнопка звала бы жать её вместо того, чтобы пойти за письмом.
 */
export function CheckMailPage() {
  const session = useSession()

  // Тот же адрес, что и на экране кода, и по той же причине: письмо ушло
  // на почту вошедшего. Нет сеанса — нет и адреса, и экран говорит «на вашу
  // рабочую почту» вместо конкретного чужого ящика.
  const mailbox = session?.email || "вашу рабочую почту"

  return (
    <AuthShell
      title="Проверьте почту"
      subtitle={`Мы отправили письмо на ${mailbox}. Перейдите по ссылке из письма, чтобы подтвердить адрес и открыть кабинет. Ссылка живёт двадцать четыре часа.`}
      stepsLabel="ЧТО БУДЕТ ДАЛЬШЕ"
    >
      <div className="flex items-center gap-5">
        {/* Своего экрана у повторной отправки нет: письмо уходит молча, и
            плашка «письмо отправлено» здесь была бы выдумкой, а не продуктом. */}
        <Button variant="secondary" size="lg" data-action="письмо отправлено ещё раз">
          Отправить письмо ещё раз
        </Button>
        <AuthAside
          question="Письмо не пришло за пять минут?"
          action="Проверьте папку «Спам»"
        />
      </div>
    </AuthShell>
  )
}

/**
 * Приглашение сотрудника.
 *
 * **Роль объяснена до принятия, а не после.** «Вы видите выдачу, свои подборки
 * и свои раскрытия; баланс, отчёты и журнал доступа видит только руководитель» —
 * человек соглашается, понимая границы, и не удивляется потом, что чего-то
 * не видит.
 *
 * **Кто приглашает и в какое агентство — это данные приглашения, то есть
 * сервера, которого пока нет.** Раньше на их месте стояли образцы из макета:
 * заголовок звал по имени в конкретное агентство, а почта была нарисована
 * и подписана «изменить нельзя». Держать это обещание было нечем, и человек
 * принимал приглашение под чужим именем. Теперь имя и почту вводит тот, кто
 * пришёл по ссылке, а чужая вывеска не называется вовсе.
 */
export function InvitePage() {
  const navigate = useNavigate()
  const { signUp } = useSessionActions()
  const [name, setName] = useState("")
  const [email, setEmail] = useState("")
  const [password, setPassword] = useState("")
  const [accepted, setAccepted] = useState(false)

  const ready = accepted && name.trim() !== "" && email.trim() !== ""

  /**
   * Принять приглашение — значит завести сеанс и попасть на первый вход
   * сотрудника, а не в общую выдачу.
   *
   * Экран `/first-run/employee` отвечает ровно на те три вопроса, которые
   * возникают у человека в эту секунду: сколько я могу раскрыть, что уже
   * настроено до меня, чьи деньги я трачу.
   *
   * Роль в демонстрационном сеансе одна — руководитель: разделения прав
   * за экранами пока нет, и подделывать его здесь значило бы обещать
   * ограничения, которых продукт ещё не исполняет.
   *
   * Название агентства уходит пустым, и сеанс подставляет своё нейтральное
   * умолчание. Приглашение знает вывеску, но приглашение приходит с сервера;
   * вписать сюда конкретное название — значит завести человеку агентство,
   * которого он не заводил, и повесить чужую вывеску в шапке кабинета.
   */
  const accept = () => {
    if (!ready) return
    void signUp({ name, email, agency: "" })
    void navigate({ to: "/first-run/employee" })
  }

  return (
    <AuthShell
      title="Вас пригласили в агентство"
      subtitle="Роль «агент»: вы видите выдачу, свои подборки и свои раскрытия. Баланс агентства, отчёты и журнал доступа видит только руководитель."
      narrow
      stepsLabel="ЧТО БУДЕТ ДАЛЬШЕ"
      pricesLabel="ЗА ЧТО ПЛАТИТ АГЕНТСТВО"
      prices={[
        {
          value: "199 ₽",
          note: "за раскрытый контакт. Списывается со счёта агентства, не с вашего.",
        },
        {
          value: "3 000 ₽ в месяц",
          note: "за доступ агентства целиком. Вас это не касается.",
        },
      ]}
    >
      <div className="flex w-160 flex-col gap-5">
        <div className="flex w-full gap-5">
          <AuthField
            label="ФАМИЛИЯ И ИМЯ"
            value={name}
            onChange={setName}
            name="name"
            placeholderText="Как вас записать в агентстве"
          />
          {/* Поле было нарисованным и говорило «адрес из приглашения, изменить
              нельзя». Держать это обещание должен сервер, которого нет,
              а нарисованный чужой адрес заводил сеанс не тому, кого звали.
              Живое поле честнее: человек вводит ту почту, в которую пришло
              письмо, и по ней же потом входит. */}
          <AuthField
            label="РАБОЧИЙ E-MAIL"
            value={email}
            onChange={setEmail}
            name="email"
            type="email"
            autoComplete="email"
            placeholderText="почта, на которую пришло приглашение"
          />
        </div>
        <AuthField
          label="ПАРОЛЬ"
          value={password}
          onChange={setPassword}
          name="password"
          type="password"
          autoComplete="new-password"
          placeholderText="Придумайте пароль"
        />
      </div>

      <div className="h-6.5" />

      {/* Отметка настоящая, и без неё приглашение не принимается. Продукт
          отдаёт телефоны живых людей: согласие на правила работы с контактами —
          это то, чем он защищён, а не формальность экрана. */}
      <div className="flex w-160 items-center gap-2.5">
        <Checkbox
          checked={accepted}
          onCheckedChange={setAccepted}
          aria-label="Принимаю оферту и правила работы с контактами"
        />
        <Typography variant="denseText" tone="default">
          Принимаю оферту и правила работы с контактами
        </Typography>
      </div>

      <div className="h-7" />

      <div className="flex items-center gap-5">
        <Button variant="primary" size="lg" onClick={accept} disabled={!ready}>
          Принять приглашение
        </Button>
        <AuthAside
          question="Это приглашение не для вас?"
          action="Отклонить"
          dataAction="приглашение отклонено"
        />
      </div>
    </AuthShell>
  )
}

/**
 * Доступ закрыт.
 *
 * **Экран отвечает на три вопроса сразу, и это редкий случай, когда так надо.**
 * Первый: дело не в пароле — «почта и пароль верные». Второй: кто закрыл —
 * руководитель агентства. Третий, который человек постесняется задать: что
 * с моими раскрытиями — «остались у агентства: 199 ₽ за них платило агентство,
 * а не вы».
 *
 * **Имя руководителя, его почта, название агентства и дата отключения сюда
 * не подставляются.** Всё это приходит вместе с решением о закрытии, то есть
 * с сервера. Раньше на их месте стояли образцы из макета, и человек, которого
 * только что отключили, читал про незнакомое лицо и день, в который ничего
 * не происходило. Пустая строка тут дешевле выдумки: оба действия работают
 * и без имени.
 *
 * Панель справа здесь короче: цен и состава на ней нет вовсе. Человеку,
 * которого только что отключили, не рассказывают, что входит в тариф.
 */
export function AccessClosedPage() {
  return (
    <AuthShell
      title="Доступ закрыт"
      subtitle="Руководитель агентства закрыл ваш доступ. Почта и пароль верные — дело не в них. Раскрытые вами контакты остались у агентства: 199 ₽ за них платило агентство, а не вы."
      stepsLabel="ЧТО ЭТО ЗНАЧИТ"
      showPricing={false}
      steps={[
        { title: "Кабинет закрыт", note: "выдача, подборки и журнал больше не открываются" },
        {
          title: "Контакты остались у агентства",
          note: "их раскрывали за деньги агентства, а не за ваши",
        },
        {
          title: "Личные данные — по заявлению",
          note: "имя, почта и телефон удаляются по вашему обращению",
        },
      ]}
      protection="Журнал доступа остаётся у агентства: кто и когда открывал контакты. Это требование закона, а не решение руководителя."
    >
      {/* Оба действия ведут наружу продукта: одно в почту руководителя, второе
          в обращение на удаление данных. Своих экранов у них нет и быть
          не может — человек сюда уже не вернётся, кабинет для него закрыт.
          Поэтому действия названы и ничего не рисуют.

          Подписи «кому пишем» под кнопкой больше нет: адрес руководителя
          знает сервер, а не экран. Действие от этого не сломалось — письмо
          уходит тому, кто закрыл доступ, и раньше строка лишь называла его
          вслух. Ряд стал таким же, как на трёх соседних экранах: кнопка
          и пара «подпись — действие». */}
      <div className="flex items-center gap-5">
        <Button variant="secondary" size="lg" data-action="письмо руководителю агентства">
          Написать руководителю
        </Button>
        <AuthAside
          question="Не хотите оставлять свои данные?"
          action="Удалить мои данные"
          dataAction="запрошено удаление персональных данных"
        />
      </div>
    </AuthShell>
  )
}
