import { DISCLOSURE_PRICE } from "@/features/auth"
import { groupDigits, plural } from "@/features/listings"

/**
 * ДЕНЬГИ СЛОВАМИ · то, что обязано совпадать между окном и листом.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Пять состояний денег нарисованы дважды — окном на компьютере и листом
 * на телефоне: «платёж не прошёл» (`d0BrE` · `s4xQF`), «подписка не продлена»
 * (`ISKdX` · `oY6jq`), «дневной лимит исчерпан» (`ALSnR` · `HRED4`),
 * «запросить пополнение» (`V9TDoV` · `PkIhp`), «лимит возвратов исчерпан»
 * (`uzDok` · `exztG`).
 *
 * У окна и у листа разная геометрия, но ОДНА правда про одни деньги. Напиши
 * её дважды — и первая же правка формулировки разойдётся между платформами:
 * телефон пообещает разбор за сутки, компьютер за рабочий день, и агентство
 * получит два разных обещания про один и тот же возврат. Поэтому текст живёт
 * здесь один раз, а платформы — оболочки вокруг него.
 *
 * Тот же приём и по той же причине, что `collection-off-text.ts`.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ПОЧЕМУ `.ts`, А НЕ РЯДОМ С ЭКРАНОМ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Файл с компонентами экспортирует только компоненты, иначе ломается быстрая
 * перезагрузка. `SUBSCRIPTION_PRICE` жил внутри `balance-screens.tsx` и наружу
 * выйти не мог — а окну «Доступ приостановлен» нужна ровно та цена, что стоит
 * в ряде ключевых цифр баланса.
 *
 * ЗДЕСЬ ЛЕЖИТ ТОЛЬКО ТО, ЧТО ДЕЛЯТ РАЗНЫЕ ФАЙЛЫ. Текст, общий у окна и листа
 * внутри одного файла, остаётся в нём: лишний переезд прячет строку от того,
 * кто её правит.
 */

/**
 * Доступ агентства — 3 000 ₽ в месяц. Вторая и последняя цена продукта.
 *
 * Стоит в ряде ключевых цифр баланса и на кнопке «Оплатить 3 000 ₽» в обоих
 * состояниях приостановленного доступа. Кнопка, зовущая заплатить, обязана
 * называть ровно ту сумму, которую агентство читает у себя на счёте.
 */
export const SUBSCRIPTION_PRICE = 3000

/**
 * «хватит на 43 раскрытия» — рубли переводятся в работу отдела.
 *
 * Руководитель не считает в рублях: он считает, на сколько дней работы отдела
 * хватит остатка. Поэтому пересчёт идёт рядом с каждой суммой — в шапке
 * баланса, в подтверждении пополнения, в запросе пополнения.
 *
 * Копий этой функции в продукте было три, написанных порознь и совпадавших
 * случайно. Первая же смена цены раскрытия развела бы экран баланса
 * с подтверждением, которое этот экран сам и показывает.
 */
export function disclosuresFor(amount: number) {
  const count = Math.floor(amount / DISCLOSURE_PRICE)
  return `${count} ${plural(count, "раскрытие", "раскрытия", "раскрытий")}`
}

/**
 * Что продолжает работать, когда раскрытие остановлено.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Слово в слово то, что уже написано в плашке «Баланс агентства 0 ₽»
 * (`BalanceStoppedBar`, кадр `GKHtA`). Причины у остановки две — кончились
 * деньги на счёте и не продлилась подписка, — а последствие ровно одно, и
 * человек обязан прочитать про него одинаково.
 *
 * Без этой строки «раскрытие контактов остановлено» читается как «кабинет
 * сломался целиком»: агент закрывает вкладку и не узнаёт, что выдача, фильтры
 * и уже оплаченные контакты на месте. Из четырёх перечисленных вещей третья
 * важнее всех — за неё уже заплачено, — и сокращать список нельзя ради длины.
 *
 * **Плашка пока держит свою копию строки.** Она живёт в `features/cabinet`,
 * этой правкой не затронутой; чтобы копий стало ноль, ей нужно забрать строку
 * отсюда — это названо в отчёте отдельным пунктом.
 */
export const ACCESS_KEEPS_WORKING =
  "Выдача, фильтры, уже раскрытые контакты и звонки продолжают работать."

/**
 * «Платёж не прошёл» — из `d0BrE` (окно) и `s4xQF` (лист).
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * **Первым делом сказано «деньги не списаны».** Человек, увидевший отказ
 * банка, боится не того, что услуга не куплена, а того, что деньги ушли
 * в никуда. Ответ на этот страх стоит в первом предложении.
 *
 * **Средней фразы кадра здесь нет, и это не сокращение ради краткости.**
 * В `d0BrE` стоит «Номер платежа сохранён в истории пополнений». Истории
 * неудавшихся платежей у продукта нет: журнал пополнений пишется только при
 * зачислении, и вкладка пополнений честно показывает единственное состояние —
 * «Зачислено». Человек пошёл бы искать номер платежа и не нашёл бы ни строки.
 * Лист `s4xQF` нарисован уже без этой фразы — то есть файл сам от неё отказался.
 */
export const PAYMENT_FAILED_TEXT =
  "Банк отклонил операцию, деньги не списаны. Попробуйте другую карту или выставьте счёт юрлицу."

/**
 * «Подписка 3 000 ₽ не продлена…» — из `ISKdX` (окно) и `oY6jq` (лист).
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * **Дата необязательна, и это контракт, а не поблажка.** В кадрах стоит
 * «не продлена 1 августа», но платёжного сервиса за подпиской нет: продукт
 * не знает ни дня списания, ни дня отказа. Экран тарифа уже принял по этому
 * вопросу решение — там на месте даты прочерк, а не правдоподобное число.
 *
 * Поэтому дата приходит снаружи: у того, кто узнает её первым (платёжный
 * сервис), она будет, и фраза станет полной сама. Пока её нет, предложение
 * заканчивается точкой — и не врёт. Выдумать дату в вызывающем экране значило
 * бы просто перенести враньё на файл дальше.
 */
export function accessStoppedText(dueOn?: string) {
  const when = dueOn === undefined || dueOn === "" ? "" : ` ${dueOn}`
  return `Подписка ${groupDigits(SUBSCRIPTION_PRICE)} ₽ не продлена${when}. Раскрытие контактов остановлено. ${ACCESS_KEEPS_WORKING}`
}

/**
 * «Запросить пополнение» — из `V9TDoV` (окно) и `PkIhp` (лист).
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * **Это единственное, что агент может сделать с общим счётом.** Вносить
 * деньги, выставлять счёт на юрлицо и получать закрывающие документы может
 * только руководитель: у агента нет ни доступа к реквизитам, ни права
 * обязывать агентство платить. Поэтому у него не урезанное «Пополнить»,
 * а своё настоящее действие.
 *
 * **«Получит уведомление» из кадров смягчено до «увидит».** Писем и пушей
 * продукт не шлёт, и это уже сказано вслух дважды: шапка кабинета отвечает
 * на этот же запрос «Руководителю ПОКАЗАНО, что нужно пополнить счёт», плашка
 * нулевого баланса — «письма продукт не шлёт, и обещать отправку нечем».
 * Окно, обещающее уведомление, и расписка, обещающая показ, — это два разных
 * ответа на одно нажатие.
 *
 * **Остаток назван числом не для полноты.** Руководитель и агент спорят
 * не о том, кончились ли деньги, а о том, срочно ли это. «8 610 ₽, это
 * 43 раскрытия» отвечает на второй вопрос, «мало денег» — ни на один.
 * Слово «агентства» обязательно: счёт общий, и в этом вся суть просьбы.
 */
export function requestTopUpText(balance: number) {
  return `Руководитель увидит, что счёт нужно пополнить. Сейчас на счёте агентства ${groupDigits(balance)} ₽, это ${disclosuresFor(balance)}.`
}

/**
 * «Сегодня открыто 5 из 5…» — из `ALSnR` (окно) и `HRED4` (лист).
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Три факта, и каждый отвечает на свой вопрос: сколько уже потрачено, когда
 * отпустит, к кому идти. Убери любой — и остаётся запрет без выхода.
 *
 * «Обнулится завтра в 00:00» — не оборот речи, а правило продукта, записанное
 * там же, где лимит и назначают: «счётчик обнуляется в 00:00, неизрасходованное
 * не переносится».
 *
 * **Имя руководителя приходит из состава агентства, а не вписано.**
 * «Смирнова Ирина» в кадрах — образец текста: агенту чужого агентства она
 * ничего не говорит, а своего руководителя он бы не увидел. Если состав ещё
 * не записан, имени нет — и фраза короче, а не называет постороннего. Пустая
 * строка здесь обычное дело, а не поломка, поэтому ветка на неё есть.
 */
export function dailyLimitText(used: number, limit: number, owner: string) {
  const head = `Сегодня открыто ${used} из ${limit}. Лимит обнулится завтра в 00:00.`
  if (owner === "") return `${head} Изменить его может только руководитель агентства.`
  return `${head} Изменить его может только руководитель, ${owner}.`
}
