/**
 * Четыре статуса, которые агентство ставит руками.
 *
 * **Стоп-листа в списке нет, и это главное в окне.** Он приходит
 * от собственника через `serch.ru/stop` и снимается только им; поставить его
 * руками нельзя никому, включая руководителя. Будь он пятой строкой,
 * агентство однажды поставило бы его само — и объект исчез бы из работы
 * навсегда без ведома собственника.
 *
 * Набор и порядок совпадают с `STATUSES` в `BulkDialogs.tsx`.
 */
export const BULK_STATUSES = [
  { id: "free", label: "Свободен" },
  { id: "in-progress", label: "В работе" },
  { id: "called", label: "Прозвонен" },
  { id: "refused", label: "Отказ" },
] as const

export type BulkStatusId = (typeof BULK_STATUSES)[number]["id"]

/** Заголовок окна смены статуса: «Сменить статус у 12 объектов». */
export function bulkStatusTitle(count: number): string {
  return `Сменить статус у ${count} ${count === 1 ? "объекта" : "объектов"}`
}

