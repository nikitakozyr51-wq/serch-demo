/** Заголовок окна назначения: одному объекту — без числа, дюжине — с числом. */
export function assignAgentTitle(count: number): string {
  return count === 1 ? "Назначить объект агенту" : `Назначить ${count} объектов агенту`
}

/**
 * Объяснение под заголовком.
 *
 * Вторая фраза — «Статус объекта принадлежит агентству, а не человеку» —
 * есть в компьютерном кадре `jUJgJ` и пропущена в телефонном `ZQvsE`.
 * Пропуск не решение: назначение и статус путают постоянно, и снять это
 * объяснение на телефоне значило бы объяснить только половине людей.
 */
export function assignAgentText(count: number): string {
  const subject = count === 1 ? "Объект перейдёт" : "Объекты перейдут"
  const appears = count === 1 ? "он появится" : "они появятся"
  return `${subject} в работу выбранному агенту, и ${appears} у него на экране «Сегодня». Статус объекта принадлежит агентству, а не человеку.`
}

/** Некому назначать: в агентстве один человек. */
export const ASSIGN_AGENT_EMPTY =
  "Назначать некому: в агентстве вы один. Пригласите сотрудника в разделе «Агентство → Сотрудники»."

/**
 * Подпись под именем в списке людей: «агент · до 30 в день».
 *
 * Собрана здесь, а не в экране: ту же строку строит выдача на компьютере,
 * когда открывает окно назначения. Две копии одной подписи разошлись бы
 * на первом же новом ограничении.
 */
export function personNote(person: { role: "owner" | "agent"; limit: number | null }): string {
  if (person.role === "owner") return "руководитель · без лимита"
  return `агент · ${person.limit === null ? "без лимита" : `до ${person.limit} в день`}`
}

/**
 * Заголовок листа подборки: «Добавить 12 объектов».
 *
 * Слова «в подборку» на телефоне в заголовке нет — они в объяснении ниже.
 * Так в кадре `u2WQZ`: на 390 длинный заголовок переносится на вторую строку
 * и отталкивает список вниз.
 */
export function collectionPickTitle(count: number, objects: string): string {
  return `Добавить ${count} ${objects}`
}

