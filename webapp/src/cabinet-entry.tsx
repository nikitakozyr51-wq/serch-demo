import { Navigate } from "@tanstack/react-router"

import { useSession } from "@/features/auth"

/**
 * Дверь кабинета: что происходит по адресу `/app/`.
 *
 * Человек приходит сюда с лендинга, из закладки или по ссылке от коллеги,
 * и ответ должен быть один из двух: он уже вошёл — значит на сохранённые
 * поиски, не вошёл — значит на вход. Третьего осмысленного варианта нет:
 * пустая страница «кабинет» без содержимого только тратит нажатие.
 *
 * **Главной стали поиски, а не «Сегодня».** «Сегодня» — экран возвратов
 * к работе: перезвонить, дожать, закрыть. У агентства, созданного минуту
 * назад, возвращаться не к чему, и продукт начинался с пустого экрана.
 * Поиски начинаются с вопроса «что вы ищете» и четырёх готовых ответов,
 * а у того, кто уже работает, — со списка того, что принесло новое.
 *
 * **Почему не шаблонная главная.** До этой правки корень отдавал страницу
 * из заготовки проекта, которая проверяет сеанс на сервере. Сервера за
 * демонстрацией нет, запрос падал, и человек, нажавший на лендинге «Создать
 * агентство», видел «Session check is temporarily unavailable» вместо
 * продукта. В разработке это не проявлялось: там открывали сразу нужный
 * адрес, а не корень.
 *
 * Шаблонные страницы никуда не делись — они живут на своих адресах
 * (`/signup`, `/forgot-password`) до тех пор, пока за формами не появится
 * настоящая отправка. Просто корень им больше не принадлежит.
 */
export function CabinetEntryPage() {
  const session = useSession()

  if (session) return <Navigate to="/searches" replace />

  return <Navigate to="/login" search={{ returnTo: undefined }} replace />
}
