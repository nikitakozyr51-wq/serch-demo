import { Button } from "@/components/controls/Button"
import { DISCLOSURE_PRICE, useSession } from "@/features/auth"
import { groupDigits, plural } from "@/features/listings"
import { MobileOverlaySheet } from "@/mobile-sheet-parts"
import { notifyDone } from "@/platform/notify"

/**
 * Четыре листа про деньги, которые НЕ двинулись.
 *
 * `PkIhp` запросить пополнение · `s4xQF` платёж не прошёл ·
 * `oY6jq` подписка не продлена · `HRED4` дневной лимит исчерпан.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ЧЕМ ЭТИ ЧЕТЫРЕ ОТЛИЧАЮТСЯ ОТ `money-confirmations.tsx`
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Тот файл показывает, что деньги ушли или вернулись, — след, который обязан
 * дождаться, пока его прочтут. Эти четыре показывают, что деньги НЕ двинулись,
 * и у каждого есть выход: попросить, повторить, оплатить, подождать до полуночи.
 * Поэтому у всех четырёх две кнопки, а не одна: остановка без выхода — это
 * тупик, а не состояние.
 *
 * **Красного здесь нет ни на одной кнопке, и это правило, а не вкус.** Акцент
 * в продукте означает «сейчас спишутся деньги»; ни один из четырёх листов
 * ничего не списывает. Даже «Оплатить 3 000 ₽» идёт графитом: она ведёт
 * к оплате, а не совершает её.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ТРИ ИЗ ЧЕТЫРЁХ ПОКА НИОТКУДА НЕ ОТКРЫВАЮТСЯ, И ЭТО НАЗВАНО ВСЛУХ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Открывается сегодня только «Запросить пополнение»: право агента на этот
 * запрос уже описано в шапке кабинета на компьютере, и на телефоне оно
 * такое же. Остальным трём нужен источник события, которого в продукте нет:
 *
 * 1. **Платёж не прошёл** — платёжного сервиса нет вовсе, `topUp()` зачисляет
 *    деньги молча и всегда. Выдумать здесь отказ банка значило бы выдумать
 *    банк.
 * 2. **Подписка не продлена** — даты списания продукт не знает; это записано
 *    и на экране тарифа: «Дату следующего списания знает платёжный сервис,
 *    которого нет».
 * 3. **Дневной лимит исчерпан** — лимит сотруднику ставится, но `disclose()`
 *    его не проверяет: раскрытие останавливается только по нулевому остатку.
 *    Пока проверки нет, до листа нельзя дойти ни одним нажатием.
 *
 * Что нужно дописать в чужих файлах, перечислено в отчёте. Листы собраны
 * целиком и ждут одного вызова каждый.
 */

/** «43 раскрытия», «100 раскрытий», «251 раскрытие» — счёт со склонением. */
function disclosuresFor(rubles: number) {
  const count = Math.floor(rubles / DISCLOSURE_PRICE)
  return `${count} ${plural(count, "раскрытие", "раскрытия", "раскрытий")}`
}

/**
 * МОБАЙЛ · Запросить пополнение (`PkIhp`).
 *
 * **У агента нет права пополнять счёт, и лист говорит ровно о том, что он
 * может.** Счёт общий и принадлежит агентству; вносить деньги, выставлять
 * счёт на юрлицо и получать закрывающие может только руководитель. Это
 * правило уже описано в шапке кабинета на компьютере, и телефон его
 * повторяет, а не переизобретает.
 *
 * Остаток называется числом и переводится в раскрытия: агент просит не
 * «денег вообще», а звонков, которых ему не хватит. Оба числа настоящие,
 * из сеанса, — вписанные в кадре 8 610 ₽ и 43 раскрытия не двигались бы
 * ни от одного списания.
 */
function TopUpRequestSheet({
  position,
  onClose,
}: {
  position?: "fixed" | "absolute"
  onClose: () => void
}) {
  const session = useSession()
  const balance = session?.balance ?? 0

  return (
    <MobileOverlaySheet
      label="Запросить пополнение"
      title="Запросить пополнение"
      text={`Руководитель получит уведомление. Сейчас на счёте ${groupDigits(balance)} ₽, это ${disclosuresFor(balance)}.`}
      position={position}
      onClose={onClose}
      actions={
        <>
          {/*
            Слова ответа взяты у собранного близнеца — шапки кабинета
            на компьютере, где тот же запрос отвечает «Руководителю показано,
            что нужно пополнить счёт». «Показано», а не «отправлено»: писем
            продукт не шлёт, и обещать доставку нечем.
          */}
          <Button
            variant="primary"
            size="lg"
            block
            onClick={() => {
              notifyDone("Руководителю показано, что нужно пополнить счёт")
              onClose()
            }}
          >
            Отправить запрос
          </Button>
          <Button variant="quiet" size="lg" block onClick={onClose}>
            Отмена
          </Button>
        </>
      }
    />
  )
}

/**
 * МОБАЙЛ · Платёж не прошёл (`s4xQF`).
 *
 * **Первое, что говорит лист, — «деньги не списаны».** Человек, увидевший
 * отказ банка, боится не того, что услуга не куплена, а того, что деньги
 * ушли в никуда. Ответ на этот страх стоит в первом предложении, а не
 * в поддержке.
 *
 * Второй выход не «попробовать ещё раз то же самое», а другая дорога:
 * счёт юрлицу. Карта могла отказать по причине, которая повторится
 * и на второй попытке, — лимит банка, зарубежный эквайринг, корпоративная
 * карта без интернет-платежей.
 */
function PaymentFailedSheet({
  position,
  onRetry,
  onInvoice,
  onClose,
}: {
  position?: "fixed" | "absolute"
  /** Повторить тот же платёж той же картой. */
  onRetry: () => void
  /** Уйти на счёт юрлицу — другая дорога, а не вторая попытка. */
  onInvoice: () => void
  onClose: () => void
}) {
  return (
    <MobileOverlaySheet
      label="Платёж не прошёл"
      title="Платёж не прошёл"
      text="Банк отклонил операцию, деньги не списаны. Попробуйте другую карту или выставьте счёт юрлицу."
      position={position}
      onClose={onClose}
      actions={
        <>
          <Button variant="primary" size="lg" block onClick={onRetry}>
            Повторить
          </Button>
          {/* «Выставить счёт» стоит второй, но это не отмена: у листа нет
              кнопки выхода вовсе. Отказ платежа не то состояние, из которого
              выходят молча, — деньги агентству всё ещё нужны. */}
          <Button variant="quiet" size="lg" block onClick={onInvoice}>
            Выставить счёт
          </Button>
        </>
      }
    />
  )
}

/**
 * МОБАЙЛ · Подписка не продлена (`oY6jq`).
 *
 * Заголовок называет последствие — «Доступ приостановлен», — а не событие
 * «подписка не продлена». Человек открывает телефон, чтобы работать, и первое,
 * что ему нужно знать, это что именно у него отняли.
 *
 * **Вторая строка перечисляет то, что продолжает работать, и она не
 * вежливость.** Без неё «раскрытие остановлено» читается как «кабинет
 * сломался целиком». Ровно тем же порядком собрана плашка нулевого баланса
 * на компьютере: что случилось, что при этом работает, что делать.
 *
 * **Дата приходит снаружи и не выдумывается здесь.** Числа следующего
 * списания продукт не знает — за ним нет платёжного сервиса, — и «1 августа»
 * из кадра было образцом текста. Тот, кто узнает дату, её и передаст.
 */
function SubscriptionLapsedSheet({
  dueOn,
  position,
  onPay,
  onClose,
}: {
  /** Когда подписка должна была продлиться: «1 августа». Знает платёжный сервис. */
  dueOn: string
  position?: "fixed" | "absolute"
  onPay: () => void
  onClose: () => void
}) {
  return (
    <MobileOverlaySheet
      label="Доступ приостановлен"
      title="Доступ приостановлен"
      text={`Подписка 3 000 ₽ не продлена ${dueOn}. Раскрытие остановлено. Выдача, фильтры и звонки работают.`}
      position={position}
      onClose={onClose}
      actions={
        <>
          {/* Графит, а не акцент: кнопка ведёт к оплате, а не списывает.
              Красным в этом продукте красится ровно один жест — раскрытие
              контакта за 199 ₽. */}
          <Button variant="primary" size="lg" block onClick={onPay}>
            Оплатить 3 000 ₽
          </Button>
          <Button variant="quiet" size="lg" block onClick={onClose}>
            Отмена
          </Button>
        </>
      }
    />
  )
}

/**
 * МОБАЙЛ · Дневной лимит исчерпан (`HRED4`).
 *
 * **Лист отвечает на три вопроса и ни на один лишний:** сколько уже открыто,
 * когда лимит вернётся и кто может его поменять. Имя руководителя здесь
 * не украшение — это единственный человек, к которому агенту идти, и без
 * имени лист заканчивался бы тупиком «обратитесь к администратору».
 *
 * Ни одна из двух кнопок ничего не списывает, поэтому обе не акцентные.
 * «Понятно» стоит второй: закрыть лист человек догадается сам, а вот то,
 * что лимит можно попросить увеличить, он узнаёт отсюда.
 */
function DailyLimitReachedSheet({
  used,
  limit,
  owner,
  position,
  onClose,
}: {
  /** Сколько контактов агент открыл сегодня. Считается по журналу раскрытий. */
  used: number
  /** Дневной лимит агента. Безлимит до этого листа не доходит. */
  limit: number
  /** Кто может лимит поменять: руководитель агентства, по имени. */
  owner: string
  position?: "fixed" | "absolute"
  onClose: () => void
}) {
  return (
    <MobileOverlaySheet
      label="Лимит на сегодня исчерпан"
      title="Лимит на сегодня исчерпан"
      text={`Открыто ${used} из ${limit}. Лимит обнулится завтра в 00:00. Изменить его может только ${owner}.`}
      position={position}
      onClose={onClose}
      actions={
        <>
          {/* Тот же ответ и теми же словами, что у запроса пополнения:
              агент просит руководителя, продукт показывает это руководителю
              и не обещает письма, которого не отправляет. */}
          <Button
            variant="primary"
            size="lg"
            block
            onClick={() => {
              notifyDone("Руководителю показано, что вам нужен больший дневной лимит")
              onClose()
            }}
          >
            Попросить увеличить лимит
          </Button>
          <Button variant="quiet" size="lg" block onClick={onClose}>
            Понятно
          </Button>
        </>
      }
    />
  )
}

export {
  DailyLimitReachedSheet,
  PaymentFailedSheet,
  SubscriptionLapsedSheet,
  TopUpRequestSheet,
}
