import { clsx, type ClassValue } from "clsx"
import { extendTailwindMerge } from "tailwind-merge"

/**
 * Ступени кегля, названные числом: 11, 13 и плотная 20.
 *
 * `tailwind-merge` разбирает `text-*` последним правилом: всё, что он
 * не узнал по имени, считается цветом. Поэтому `text-11` рядом с цветовым
 * `text-text-dense` молча выбрасывался как «второй цвет», и подпись
 * рисовалась унаследованным кеглем 16 вместо 11 — сразу на девяти вариантах,
 * включая заголовок над каждой колонкой каждой таблицы кабинета.
 *
 * CSS при этом был верным, класс в сборке был, линт и типы молчали:
 * значение терялось между `cva` и разметкой. Ступени, названные числом,
 * обязаны быть перечислены здесь явно — иначе они существуют только в CSS.
 */
/**
 * Ступени размеров, названные словом: `h-ctl-md`, `w-sidebar`, `w-filters`.
 *
 * Их беда обратная беде кегля: `tailwind-merge` их не узнаёт **и не относит
 * никуда**, поэтому они не снимают чужое и чужое не снимает их. Пара
 * `h-full h-ctl-md` доезжает до разметки целиком, и побеждает не та, что
 * написана последней, а та, что стоит позже в собранном CSS. Замер показал:
 * `.h-full` там ниже всех ступеней контрола, то есть конфликт разрешился бы
 * против нас.
 *
 * Живой пары в коде сегодня нет. Механизм при этом заряжен, а комментарий
 * в `Button.tsx` прямо опирается на то, что конфликт разрешает `cn`.
 */
const twMerge = extendTailwindMerge({
  extend: {
    classGroups: {
      "font-size": [{ text: ["11", "13", "20-tight"] }],
      h: [{ h: ["ctl-xs", "ctl-sm", "ctl-md", "ctl-lg", "ctl-chip", "row-obj", "row-tbl", "row-head", "header"] }],
      w: [{ w: ["col-96", "col-120", "col-144", "col-168", "col-216", "sidebar", "filters", "content", "results"] }],
    },
  },
})

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs))
}
