/**
 * Телефоны демонстрации.
 *
 * **Ни один номер в продукте не должен принадлежать живому человеку.**
 * До этой правки на лендинге и в кабинете стояли десять номеров в кодах
 * 911, 921 и 981 — это настоящие петербургские диапазоны МТС и МегаФона,
 * и каждый такой номер прямо сейчас может быть чьим-то.
 * Публичная страница с ним — это чужой телефон, выложенный в интернет,
 * и звонок от любопытного зрителя живому человеку.
 *
 * **Что выбрано и почему именно так.** Официального «диапазона для примеров»,
 * как британский 07700 900xxx, в России нет. Поэтому берётся форма, которая
 * читается как телефон, но не может быть выдана абоненту:
 *
 *     +7 900 000-XX-XX
 *
 * Абонентские блоки внутри кода DEF операторам выделяются не с нуля, и номер
 * с тремя нулями в начале абонентской части ни на что не похож, кроме образца.
 * Полной гарантии без реестра Роскомнадзора не даёт никто, поэтому рядом
 * стоит второе правило, которое гарантию и обеспечивает:
 *
 * **Ни один телефон в демонстрации не является ссылкой `tel:`.** Номер можно
 * прочитать и скопировать, но нельзя позвонить одним нажатием. Случайного
 * звонка не будет даже при самом неудачном совпадении.
 *
 * Когда за продуктом появятся настоящие данные, номера придут из базы,
 * а этот модуль останется только для стендов.
 */

/** Из чего собран номер: код 900 и абонентская часть, начинающаяся с 000. */
const CODE = "900"
const BLOCK = "000"

/**
 * Устойчивый номер по любому ключу: одинаковый ключ — одинаковый номер.
 *
 * Нужна именно устойчивость, а не случайность: объект «Ленская ул., 10»
 * обязан показывать один и тот же телефон на выдаче, в карточке, в прозвоне
 * и в журнале доступа. Иначе демонстрация разваливается на глазах —
 * человек видит разные номера у одного собственника.
 */
export function demoPhone(key: string): string {
  let hash = 2166136261
  for (let i = 0; i < key.length; i += 1) {
    hash ^= key.charCodeAt(i)
    hash = Math.imul(hash, 16777619) >>> 0
  }
  const tail = hash % 10000
  const a = String(Math.floor(tail / 100)).padStart(2, "0")
  const b = String(tail % 100).padStart(2, "0")
  return `+7 ${CODE} ${BLOCK}-${a}-${b}`
}

/**
 * Номер, скрытый до раскрытия: `+7 900 ··· ·· 42`.
 *
 * Видны код и две последние цифры — ровно столько, чтобы человек узнал свой
 * номер, если это он, и не хватило, чтобы позвонить. Так нарисовано в файле
 * и так работает продукт: за остальное платят 199 ₽.
 */
export function maskedPhone(key: string): string {
  const full = demoPhone(key)
  return `+7 ${CODE} ··· ·· ${full.slice(-2)}`
}
