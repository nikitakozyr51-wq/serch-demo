/**
 * Ссылка приглашения истекла — большой экран (`KjWAe`) и телефон (`xCg0B`).
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ПОЧЕМУ ДВА ЭКРАНА В ОДНОМ ФАЙЛЕ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Обычно в этом проекте телефон живёт отдельным файлом: мобильный экран —
 * не сжатый десктоп, а другой экран, и своя копия текста у него законна.
 * Здесь исключение, и оно ровно одно: три ответа на вопрос «что происходит
 * дальше» в обоих кадрах написаны слово в слово. Это не оформление, а
 * единственное, что человек в этом тупике получает вместо кабинета —
 * инструкция, как из него выйти. Разъехавшись, две копии стали бы двумя
 * разными обещаниями одному и тому же человеку, открывшему письмо сначала
 * на телефоне, потом на компьютере.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ЭТО ТУПИК, И У НЕГО ЕСТЬ ВЫХОД
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Тот же принцип, что у `ВХОД · Доступ закрыт`: экран, из которого нельзя
 * попасть в продукт, обязан назвать следующее действие. Здесь их два —
 * написать руководителю (он высылает приглашение заново одним нажатием)
 * и написать людям сервиса. Второе стоит последней строкой панели, а не
 * кнопкой: сначала пробуют того, кто может решить вопрос сам.
 *
 * **Третий факт отвечает на невысказанный вопрос.** «Ваши данные: ничего
 * не создано» — человек, ткнувший в мёртвую ссылку, не знает, завёлся ли
 * у него аккаунт, надо ли что-то удалять и не утекло ли что-нибудь. Пока
 * ему это не сказали, он будет думать об этом, а не о новом приглашении.
 *
 * **Ни имени руководителя, ни названия агентства, ни даты здесь нет.** Всё
 * это приходит вместе с приглашением, то есть с сервера, — а приглашение
 * как раз и протухло. Общие слова честнее правдоподобной подстановки.
 */

/** Срок жизни приглашения — условие продукта, оно же названо в тексте. */
type Fact = { when: string; what: string }

const NEXT: Fact[] = [
  {
    when: "Ссылка мертва",
    what: "Открыть кабинет по ней уже нельзя. Старая ссылка не оживает даже у того, кто её выслал.",
  },
  {
    when: "Новое приглашение",
    what: "Руководитель высылает его из раздела «Агентство → Сотрудники». Придёт на ту же почту.",
  },
  {
    when: "Ваши данные",
    what: "Ничего не создано: аккаунта по истёкшей ссылке не существует, вводить ничего не нужно.",
  },
]

const LEAD =
  "Приглашение живёт семь дней. Попросите руководителя выслать новое, это одно нажатие в разделе «Агентство»."

const LEGAL =
  "Семь дней — срок жизни приглашения. Он одинаковый для всех агентств и не настраивается."

/**
 * Столбик «что происходит дальше»: метка 11/600 капслоком и три пары
 * 13/600 + 13/500 с зазором 4. Между парами 14.
 *
 * Один и тот же на обоих экранах — меняются только поля коробки вокруг:
 * 28 на большом экране, 16 на телефоне.
 */
function NextSteps() {
  return (
    <>
      <Typography variant="columnHeader" tone="dense">
        ЧТО ПРОИСХОДИТ ДАЛЬШЕ
      </Typography>
      {NEXT.map((fact) => (
        <div key={fact.when} className="flex w-full flex-col gap-1">
          <Typography variant="numericDense" tone="default">
            <>{fact.when}</>
          </Typography>
          <Typography variant="denseText" tone="secondary">
            <>{fact.what}</>
          </Typography>
        </div>
      ))}
    </>
  )
}

