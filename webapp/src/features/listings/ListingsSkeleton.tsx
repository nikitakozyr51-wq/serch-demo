import { Typography } from "@/components/typography"
import { cn } from "@/lib/utils"

/**
 * Загрузка выдачи.
 *
 * Снято с экрана `pG4yw` «СОСТОЯНИЕ · Загрузка выдачи»: пять строк выдачи
 * в белой панели с радиусом 16. Скелет повторяет раскладку, а не намекает
 * на неё: когда данные приедут, ничего не прыгнет.
 *
 * **Колонки берутся у `ListingRow`, а не описываются числами здесь.**
 * В этой шапке стояло «пять строк по 88, колонки 16 / 432 / 596 / 748» —
 * запись времён строки шириной 908 с кадром 84 × 56. С тех пор строку
 * пересобрали: кадр стал квадратом 48, колонка действия выросла со 144
 * до 168, высота поднялась с 88 до 96, а выдача расширилась до 1200,
 * и абсолютные смещения перестали что-либо значить. Высота сошлась сама,
 * потому что приходит токеном `h-row-obj`, — и разъезд колонок никто
 * не увидел глазом. Поэтому ниже у каждой колонки стоит ровно тот же
 * класс, что и в `ListingRow`, и сверять скелет надо с ним, а не с шапкой:
 *
 *   кадр объекта  48  `size-12`
 *   объект        тянется
 *   собственник   132 `w-33`
 *   кто и статус  120 `w-30`
 *   действие      168 `w-42`
 *
 * Зазор 32 `gap-8`, поля `px-cell`, высота `h-row-obj` — оба последних
 * сами переключаются плотностью, поэтому числом их сюда и не выписываю.
 *
 * **Скелетоны, а не крутилка, и загрузка называет, чего ждёт.** Это правило
 * DESIGN.md, и файл его подтверждает: над скелетом стоит «Ищем в 4 источниках»
 * и «2 из 4 ответили · Авито и Циан». Спиннера без слов не бывает — человек
 * должен понимать, кого мы ждём и сколько уже ответило.
 *
 * Нижняя линия есть у всех пяти строк, включая последнюю: в списке с данными
 * последняя её теряет, а в скелете нет — так в файле. Разница читается как
 * «список продолжается, просто пока не приехал».
 *
 * Чего здесь **нет намеренно**: задержки 150 мс перед показом и удержания
 * минимум 400 мс. Это правила про данные, а не про вид, и заводить их
 * без сетевого слоя не на чем — сейчас показывать нечего и нечего ждать.
 */

/** Плашка скелета. Цвет из макета, мерцание из DESIGN.md — см. `index.css`. */
function Plate({ className }: { className: string }) {
  return <span aria-hidden className={cn("skeleton-plate block", className)} />
}

type ListingsSkeletonProps = {
  /** Что грузим: «Ищем в 4 источниках». */
  title?: string
  /** Насколько продвинулись: «2 из 4 ответили · Авито и Циан». */
  note?: string
  /** Сколько строк рисовать. В макете пять. */
  rows?: number
}

function ListingsSkeleton({
  title = "Ищем в 4 источниках",
  note = "2 из 4 ответили · Авито и Циан",
  rows = 5,
}: ListingsSkeletonProps) {
  const rowIndexes = Array.from({ length: rows }, (_, index) => index)

  return (
    <div data-slot="listings-skeleton" className="flex h-full w-full flex-col gap-3">
      {/* Строка состояния — та же форма, что у шапки выдачи: 36, зазор 10. */}
      <div className="flex h-9 w-full items-center gap-2.5">
        <Typography variant="rowPrice" tone="default">
          <>{title}</>
        </Typography>
        <Typography variant="denseText" tone="dense">
          <>{note}</>
        </Typography>
      </div>

      <div
        role="status"
        aria-busy="true"
        aria-label={`${title}. ${note}`}
        className="flex flex-1 flex-col overflow-hidden rounded-2xl bg-surface"
      >
        {rowIndexes.map((index) => (
          <div
            key={index}
            data-slot="skeleton-row"
            className="flex h-row-obj w-full shrink-0 items-center gap-8 border-b border-line-2 px-cell"
          >
            {/* Кадр объекта: тот же квадрат 48 с радиусом `r-control`, что
                и в настоящей строке. Тут стояло 84 × 56 — форма, от которой
                строка отказалась 10.08.2026, когда список свели к одной
                форме на телефоне и на компьютере. Скелет остался с прежним
                кадром, и текстовая колонка начиналась на 36 px левее
                настоящей: список при появлении данных дёргался, и человек
                видел не загрузку, а перестройку. Скелет обязан повторять
                КОЛОНКИ, а не намекать на них. */}
            <Plate className="size-12 shrink-0 rounded-xl" />

            <div className="flex min-w-0 flex-1 flex-col gap-2">
              <Plate className="h-4 w-50 rounded-sm" />
              <Plate className="h-3 w-70 rounded-sm" />
            </div>

            <div className="flex w-33 shrink-0 flex-col gap-2">
              {/* Радиус 2 законен: полоска высотой 5, при радиусе 6 стала бы капсулой. */}
              <Plate className="h-[5px] w-24 rounded-full" />
              <Plate className="h-[11px] w-15 rounded-sm" />
            </div>

            <div className="flex w-30 shrink-0 items-center gap-3">
              <Plate className="size-6 rounded-full" />
              <Plate className="h-6 w-21 rounded-sm" />
            </div>

            {/* Колонка действия — 168, как в строке, а не 144. Правый край
                у неё совпадал и на 144 (обе прижаты полем строки), поэтому
                разъезд и не бросался в глаза: уезжали левый край самой
                кнопки и правые края двух колонок перед ней — «собственник»
                и «кто и статус» стояли на 24 px правее настоящих.

                Капсула, а не радиус 8: и кнопка `size="sm"`, и плашка
                «недоступно» — капсулы, а скруглённый прямоугольник обещал
                форму, которой на месте скелета не появится. */}
            <Plate className="h-ctl-sm w-42 shrink-0 rounded-full" />
          </div>
        ))}
      </div>
    </div>
  )
}

export { ListingsSkeleton }
export type { ListingsSkeletonProps }
