import { useEffect, useState } from "react"

/**
 * Ширина, ниже которой колонка фильтров сворачивается.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * **Ручного тумблера нет, и это решение.** Свернул, забыл, потом удивляешься
 * выдаче: почему объектов тридцать, если в городе тысячи. Условия обязаны
 * быть видны рядом с результатом — это первая претензия к конкуренту, у
 * которого фильтр съедает 60 % высоты и полностью закрывает выдачу, пока
 * настраиваешь.
 *
 * Но довод «пусть будет видно всегда» работает, только пока есть место.
 * На ноутбуке 1280 фиксированные 260 съедают пятую часть ширины, и выдача
 * теряет колонки. Поэтому решает не человек, а окно:
 *
 * - **1360 и шире** — колонка открыта, ничего не сворачивается;
 * - **уже 1360** — колонка уходит в полоску 44 над выдачей, а открывается
 *   наложением поверх выдачи.
 *
 * Выдача при этом получает 1040 вместо 940 — ровно те 100 px, что съедала
 * колонка вместе с зазором.
 *
 * Свёрнутая полоска перечисляет сами условия. Спрятать их было бы хуже, чем
 * занять место: человек забудет, почему выдача такая.
 */
const OPEN_FROM = 1360

function query(): MediaQueryList | null {
  if (typeof window === "undefined") return null
  return window.matchMedia(`(max-width: ${OPEN_FROM - 1}px)`)
}

/** Свёрнута ли колонка фильтров прямо сейчас. */
function useFilterCollapse(): boolean {
  const [narrow, setNarrow] = useState(() => query()?.matches ?? false)

  useEffect(() => {
    const media = query()
    if (media === null) return
    const onChange = () => setNarrow(media.matches)
    onChange()
    media.addEventListener("change", onChange)
    return () => media.removeEventListener("change", onChange)
  }, [])

  return narrow
}

export { OPEN_FROM, useFilterCollapse }
