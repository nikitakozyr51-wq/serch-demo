/**
 * Режим выдачи: продажа или аренда.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Режим — не фильтр. Фильтр сужает найденное; режим меняет саму базу, единицу
 * цены и состав условий. Смешанная выдача физически нечитаема: в одной
 * колонке цены не могут стоять «8,6 млн ₽» и «70 000 ₽/мес» — это разные
 * шкалы, и глаз их не сравнивает.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ЕДИНИЦА ЖИВЁТ В ШАПКЕ КОЛОНКИ, А НЕ В КАЖДОЙ СТРОКЕ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * «Цена, ₽/мес» сверху, «70 000» в ячейке. Иначе «₽/мес» повторяется двадцать
 * четыре раза на экране и перестаёт читаться вовсе. В карточке объекта
 * единица наоборот пишется: там она встречается один раз.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ПОРОГ АНАЛОГОВ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * В аренде объявление живёт дни, а не месяцы, и аналогов может не набраться.
 * **Меньше восьми — отклонение не показывается вовсе**, в ячейке стоит
 * «мало данных». Врать про рынок хуже, чем промолчать: колонка отклонения —
 * ядро продукта, и одно неверное число в ней стоит дороже десяти пустых.
 */

type SearchMode = "sale" | "rent"

/** Порог аналогов, ниже которого отклонение не показывается. */
const ENOUGH_COMPARABLES = 8

/** Подпись колонки цены. Единица — свойство колонки, а не строки. */
const PRICE_HEAD: Record<SearchMode, string> = {
  sale: "Цена",
  rent: "Цена, ₽/мес",
}

/**
 * Цена в строке выдачи.
 *
 * У продажи — «8,6 млн ₽»: миллионы читаются только словом, семизначное
 * число глаз не разбирает. У аренды — «70 000» без единицы, разряды
 * разделены неразрывным пробелом, чтобы число не переносилось.
 */
function priceLabel(mode: SearchMode, value: number): string {
  if (mode === "rent") return value.toLocaleString("ru-RU").replaceAll(" ", " ")
  const millions = value / 1_000_000
  return `${millions.toFixed(1).replace(".", ",")} млн ₽`
}

/** Цена в карточке объекта: здесь единица пишется, она встречается один раз. */
function priceTitle(mode: SearchMode, value: number): string {
  return mode === "rent" ? `${priceLabel(mode, value)} ₽/мес` : priceLabel(mode, value)
}

export { ENOUGH_COMPARABLES, PRICE_HEAD, priceLabel, priceTitle }
export type { SearchMode }
