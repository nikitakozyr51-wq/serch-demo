import type { PhotoPlaceholderSize } from './PhotoPlaceholder'

/**
 * Размер заглушки выбирается шириной слота, а не на глаз.
 * Пороги записаны в `СИСТЕМА · Кадра нет`: до 96 — мелкий, 96–239 — средний,
 * от 240 — крупный. Мелкий несёт только значок: подписи там негде поместиться,
 * а обрезанная подпись хуже её отсутствия.
 *
 * Вынесено из файла компонента: там это ломало горячую перезагрузку —
 * файл с компонентом не должен экспортировать ничего, кроме компонентов.
 */
export function sizeForWidth(width: number): PhotoPlaceholderSize {
  if (width < 96) return 'small'
  if (width < 240) return 'medium'
  return 'large'
}
