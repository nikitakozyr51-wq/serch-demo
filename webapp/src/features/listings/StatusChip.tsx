import { StateChip, type StateTone } from "@/components/controls/StateChip"

/**
 * Чип состояния объекта: точка 6 и слово 12/500.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ПЕРЕСОБРАН 10.08.2026: ПЛАШКИ БОЛЬШЕ НЕТ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Был прямоугольник с заливкой, рамкой и радиусом — восемь состояний, восемь
 * разных плашек. На экране это читалось кнопками: «Стоп-лист» выглядел так же,
 * как контрол, по которому надо нажать, а нажимать там нечего.
 *
 * Стал компонент `xUogw`: высота 24, зазор 6, точка 6 × 6 и слово 12/500.
 * Ни заливки, ни рамки, ни радиуса — замер снят с самого компонента и с его
 * экземпляров. Смысл несёт **цвет точки**, а слово остаётся словом.
 *
 * Так чип встал туда, где состояние и есть содержание: в уведомления вместо
 * трижды повторённого «включено», в отказы вместо трёх неразличимых серых
 * строк, в строку выдачи вместо плашки, похожей на кнопку.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ЦВЕТ ТОЧКИ И ЦВЕТ СЛОВА — РАЗНЫЕ ВЕЩИ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Точка идёт глифовым тоном (`ok-glyph`, `warn-glyph`), слово — текстовым
 * (`ok-text`, `warn-text`). Это не небрежность: фигура 6 × 6 и текст 12 px
 * при одинаковом цвете читаются разной насыщенности, и в палитре проекта
 * для них поэтому заведены две ступени.
 *
 * У «Стоп-листа» точка красная, а слово остаётся `text-2`. Красное слово
 * рядом с красной точкой кричало бы вдвое, а состояние это не тревога:
 * объект просто нельзя трогать, и об этом достаточно сказать один раз.
 *
 * Состояние — один из двух ортогональных каналов строки. Второй — владелец
 * (кружок с инициалами). Кто взял читается позиционно, что происходит — чипом.
 *
 * **Набор закрыт восемью состояниями** — столько их в файле, и ни одним больше.
 */
type ListingStatus =
  | "in-progress"
  | "called"
  | "disclosed"
  | "refused"
  | "stop-list"
  | "no-phone"
  | "revoked"
  | "new"

const LABEL: Record<ListingStatus, string> = {
  "in-progress": "В работе",
  called: "Прозвонен",
  disclosed: "Раскрыт",
  refused: "Отказ",
  "stop-list": "Стоп-лист",
  "no-phone": "Номера нет",
  revoked: "Отозван",
  new: "Новый",
}

/**
 * Тон точки — по одному замеру на состояние.
 *
 * Приглушённое слово у «Отказа» и «Отозван» отличает исход, за которым
 * действия уже нет, от исходов, за которыми оно стоит: `quiet` роняет
 * подпись на `text-dense`.
 */
const TONE = {
  "in-progress": "warn",
  called: "neutral",
  disclosed: "ok",
  refused: "quiet",
  "stop-list": "danger",
  "no-phone": "neutral",
  revoked: "quiet",
  // «Новый» живёт на карточке объекта, а не в строке выдачи: там свежесть
  // говорит текстом («14 минут»), а здесь нужен ярлык.
  new: "neutral",
} as const satisfies Record<ListingStatus, StateTone>

type StatusChipProps = {
  status: ListingStatus
  /**
   * Телефонный размер: 32 вместо 24 и радиус 8 вместо 6.
   *
   * Радиус меняется вместе с высотой, а не остаётся прежним: по карте
   * от 04.08 высоте 24 отвечает r-6, а высоте 28 и 32 — r-8. Пара
   * «высота — радиус» берётся из карты целиком, поодиночке значения не ходят.
   */
  tall?: boolean
}

function StatusChip({ status, tall = false }: StatusChipProps) {
  return (
    <StateChip tone={TONE[status]} slot="status-chip" state={status} tall={tall}>
      {LABEL[status]}
    </StateChip>
  )
}

export { StatusChip }
export type { StatusChipProps, ListingStatus }
