/**
 * Тестовые кадры квартир.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ЭТО НЕ ФОТОГРАФИИ НАСТОЯЩИХ ОБЪЕКТОВ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Двенадцать интерьеров, сгенерированных в Pencil на доске «ФОТО · Тестовые
 * кадры квартир» и сжатых до 900 × 600 (`scripts/import-demo-photos.mjs`).
 * Поставлены вместо пустых мест, чтобы продукт можно было показывать: строка
 * выдачи, состоящая из одного текста, читается как таблица, а не как объект
 * недвижимости.
 *
 * **Продукт настоящие фотографии не хранит и хранить не будет.** Кадр живёт
 * ссылкой на площадку и исчезает вместе с объявлением — так устроен
 * `ListingPhoto`. Эти двенадцать заменятся первой же настоящей выгрузкой:
 * поменяется источник ссылки, а не экраны.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ПОЧЕМУ КАДР ЕСТЬ НЕ У ВСЕХ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Соблазн раздать фотографию каждому объекту велик — так витрина выглядит
 * ровнее. Но объявление без снимков это **обычное состояние**, а не сбой:
 * собственник выложил текст и телефон, и таких на площадках много. В файле
 * под это нарисованы три заглушки — `KuC1Q`, `j2uw8`, `M8WRUo`, — и раздав
 * кадры всем, мы сделали бы их недостижимыми: нарисовано, собрано, никогда
 * не показывается.
 *
 * Поэтому каждый восьмой объект остаётся без кадра. Число не выдумано из
 * красоты: это примерно та доля, с которой объявления без фото встречаются
 * в выгрузке владельца, и она держит оба состояния живыми на одном экране.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ПОЧЕМУ ВЫБОР СЧИТАЕТСЯ ИЗ АДРЕСА, А НЕ СЛУЧАЕН
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * У объекта обязан быть ОДИН и тот же кадр всегда: в выдаче, в карточке,
 * в подборке, после перезагрузки страницы и на снимке проверки. Случайный
 * выбор менял бы кадр при каждой отрисовке — квартира на Ленской была бы
 * то кухней, то балконом, и первым это заметил бы тот, кому её показывают.
 *
 * Отсюда и запрет на `Math.random` в этом файле: снимки `design:check`
 * расходились бы между запусками, и проверка начала бы падать через раз.
 */

/**
 * Имена файлов в `public/demo-photos`.
 *
 * Порядок значим: он входит в выбор кадра. Переставить строки местами —
 * значит поменять кадры у всех объектов разом.
 */
const SHOTS = [
  "kitchen-light",
  "living-sofa",
  "bedroom",
  "empty-room",
  "hallway",
  "bathroom",
  "window-view",
  "studio",
  "panel-building",
  "kitchen-living",
  "balcony",
  "kids-room",
] as const

/** Каждый восьмой объект — без кадра. См. объяснение выше. */
const WITHOUT_PHOTO_EVERY = 8

/**
 * Число из строки: одно и то же для одного и того же адреса.
 *
 * Обычный полиномиальный свёртыш по кодам знаков. Криптографии здесь не
 * нужно — нужна только устойчивость: адрес не меняется, значит и кадр
 * не меняется.
 */
function hashOf(value: string): number {
  let hash = 0
  for (let index = 0; index < value.length; index += 1) {
    hash = (hash * 31 + value.charCodeAt(index)) | 0
  }
  return Math.abs(hash)
}

/**
 * Корень, под которым отдаётся кабинет.
 *
 * На своём домене это `/app/`, в демонстрации на GitHub Pages —
 * `/serch-demo/app/`. Адрес, начинающийся со слэша, ушёл бы в корень
 * САЙТА, а не приложения: кадры молча не находились, слот показывал
 * пустой прямоугольник вместо снимка и вместо честной заглушки.
 * Ровно так и случилось при первой сборке, и поймал это замер в браузере,
 * а не глаз: слот был на месте, просто пустой.
 */
const BASE = import.meta.env.BASE_URL

/**
 * Адрес кадра для объекта — или `undefined`, если кадра у него нет.
 *
 * `undefined` здесь не ошибка и не «ещё не загрузилось»: это ответ
 * «у объявления нет снимков», и `ListingPhoto` рисует на него заглушку
 * с причиной.
 */
function photoFor(address: string): string | undefined {
  const hash = hashOf(address)
  if (hash % WITHOUT_PHOTO_EVERY === 0) return undefined
  return `${BASE}demo-photos/${SHOTS[hash % SHOTS.length]}.webp`
}

/**
 * Все кадры объекта: тот же приём, но подряд от его собственного.
 *
 * Карточка объекта показывает не один снимок, а пачку. Брать их случайно
 * нельзя по той же причине, что и один: набор обязан быть постоянным.
 * Первый кадр совпадает с тем, что показан в строке выдачи, — иначе
 * человек, нажавший на строку, попадает будто на другой объект.
 */
function photosFor(address: string, count = 4): string[] {
  const first = photoFor(address)
  if (first === undefined) return []
  const start = hashOf(address) % SHOTS.length
  return Array.from(
    { length: Math.min(count, SHOTS.length) },
    (_, index) => `${BASE}demo-photos/${SHOTS[(start + index) % SHOTS.length]}.webp`,
  )
}

export { photoFor, photosFor }
