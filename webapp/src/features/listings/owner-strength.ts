/**
 * Оценка признаков собственника словом.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Живёт отдельным файлом, а не рядом с `OwnerSignal`, по требованию быстрой
 * перезагрузки: файл, который отдаёт и компонент, и функцию, перестаёт
 * обновляться в браузере без полной перезагрузки страницы.
 *
 * Таблица одна на шкалу и на слово. Второй копии быть не должно: в режиме
 * прозвона стояло вписанное «Средние» на любой объект — то есть оценка
 * чужого собственника рядом с телефоном того, кому звонят.
 */
type OwnerStrength = "strong" | "medium" | "weak"

/**
 *   1 объявление, 1 номер    → Сильные, 3 сегмента
 *   2–3 объявления, 1 номер  → Средние, 2 сегмента
 *   2 и больше номеров       → Слабые, 1 сегмент
 */
const FILLED: Record<OwnerStrength, number> = { strong: 3, medium: 2, weak: 1 }

const WORD: Record<OwnerStrength, string> = {
  strong: "Сильные",
  medium: "Средние",
  weak: "Слабые",
}

/** Слово оценки без шкалы: там, где место есть только под слово. */
function ownerStrengthWord(strength: OwnerStrength): string {
  return WORD[strength]
}

export { FILLED, WORD, ownerStrengthWord }
export type { OwnerStrength }
