import { Outlet, useRouterState } from "@tanstack/react-router"

import { CabinetShell } from "./CabinetShell"

/**
 * Каркас кабинета, который строится ОДИН раз.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ ОН ПОЯВИЛСЯ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * До него шапка и боковое меню жили ВНУТРИ каждого экрана: `<CabinetShell>`
 * стоял в девяти файлах, и разделы агентства несли второй такой же каркас.
 * Маршруты при этом были братьями — у каждого экрана свой, общего родителя
 * не существовало.
 *
 * Из этого следовало то, на что жаловался владелец словами «весь сайт слишком
 * дёрганый»: при переходе «Сегодня → Агентство» React менял тип компонента
 * в одной позиции дерева, а значит был обязан снести поддерево целиком —
 * вместе с шапкой, боковым меню, счётчиком денег и списком поисков. Каждый
 * переход пересобирал кабинет заново.
 *
 * Анимацией это не лечится: нельзя плавно показать то, что в этот момент
 * уничтожают. Поэтому каркас поднят НАД `Outlet` и стал родительским
 * маршрутом. Совпадение родителя между переходами сохраняется, и React
 * физически не имеет права тронуть узлы шапки и меню.
 *
 * Следствия, которые получаются бесплатно:
 * — счётчик списания 199 ₽ наконец досчитывает, потому что шапка переживает
 *   переход с карточки объекта на карточку с номером;
 * — палитра и карта клавиш перестают перемонтироваться на каждом экране;
 * — подсветка пункта меню может переезжать, а не щёлкать.
 *
 * Закон движения — `docs/MOTION.md`, роль «Смена экрана».
 */

/**
 * Какой пункт меню подсвечен на этом адресе.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Раньше это значение приходило литералом с каждого экрана — `activeId="search"`
 * в девяти местах. Литерал в экране означает, что экран знает про меню; на самом
 * деле знать про меню должно меню, а экран — только про себя.
 *
 * Таблица явная, а не выведенная правилом, потому что правило здесь лгало бы
 * в трёх местах: `/first-run/search` начинается с `/first-run`, но подсвечивает
 * поиск; `/offline` не начинается ни с чего знакомого, но человек попал туда
 * из выдачи; `/profile` и первый вход не подсвечивают ничего вовсе.
 *
 * Пустая строка — законное значение: ни один пункт не подсвечен.
 */
const EXACT: Record<string, string> = {
  "/first-run/search": "search",
  "/first-run/agency": "",
  "/first-run/employee": "",
  "/offline": "search",
  "/no-rights": "",
  "/session-expired": "",
}

/** Разделы. Проверяются по порядку, первый подошедший выигрывает. */
const BY_PREFIX: readonly (readonly [string, string])[] = [
  ["/today", "today"],
  ["/searches", "search"],
  ["/search", "search"],
  ["/object", "search"],
  ["/balance", "balance"],
  ["/collections", "collections"],
  ["/agency", "agency"],
  ["/profile", ""],
] as const

function activeIdOf(pathname: string): string {
  const exact = EXACT[pathname]
  if (exact !== undefined) return exact

  for (const [prefix, id] of BY_PREFIX) {
    if (pathname === prefix || pathname.startsWith(`${prefix}/`)) return id
  }

  return ""
}

function CabinetFrame() {
  /**
   * Адрес берётся у маршрутизатора, а не у экрана.
   *
   * Здесь это безопасно, в отличие от корневой обёртки: значение идёт
   * в подсветку меню, а не в ключ перемонтирования. Меню имеет право
   * подсветиться на кадр раньше, чем приедет экран, — так человек видит,
   * что нажатие принято.
   */
  const pathname = useRouterState({ select: (state) => state.location.pathname })

  /**
   * Ключ проявления — ОТРИСОВАННЫЙ маршрут, а не адрес.
   *
   * ═══════════════════════════════════════════════════════════════════════
   *
   * Разница решает всё. Адрес маршрутизатор меняет в начале навигации,
   * а экран приезжает позже — сперва скачивается его кусок кода. Ключ
   * по адресу успевал смениться раньше, чем появлялся новый экран, и
   * 200 мс проявления доставались уходящему; входящий подменялся вовсе
   * без анимации. Список отрисованных совпадений обновляется ровно тем
   * же кадром, который показывает новый экран.
   *
   * Ключ стоит на ТЕЛЕ, а не на кабинете: шапка и меню обязаны пережить
   * переход, иначе вся эта правка бессмысленна.
   */
  const screenId = useRouterState({ select: (state) => state.matches.at(-1)?.id ?? "" })

  return (
    <CabinetShell activeId={activeIdOf(pathname)}>
      {/* Строка, а не колонка: так же лежало содержимое, когда каркас был
          внутри экрана. Выдача ставит рядом колонку фильтров и результат,
          и обёртка не имеет права сменить им направление. */}
      <div key={screenId} className="screen-in flex min-w-0 flex-1">
        <Outlet />
      </div>
    </CabinetShell>
  )
}

// Наружу уходит только компонент: файл с быстрым обновлением экрана не должен
// экспортировать ничего, кроме компонентов, иначе Vite перестаёт обновлять его
// на лету. Таблица адресов нужна только этому файлу и остаётся внутри.
export { CabinetFrame }
