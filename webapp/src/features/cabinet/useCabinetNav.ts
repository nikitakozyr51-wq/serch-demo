import { NAV } from "@/cabinet-demo-nav"
import { callbacksDue, takenNotCalled, useNow, useWorkspace } from "@/features/workspace"
import type { NavEntry } from "./CabinetSidebar"

/**
 * Боковое меню кабинета: один источник на оба каркаса.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * **Из-за двух источников владелец сказал: «не могу нажать ни на один
 * сохранённый поиск в агентстве».** И был прав буквально. `CabinetShell`
 * брал поиски из работы агентства — у них есть адрес, и они были ссылками.
 * `AgencyShell` отдавал в тот же сайдбар константы из файла навигации,
 * у которых адреса нет вовсе; сайдбар в этом случае рисует `<button>`,
 * а обработчик ему никто не передавал. Кнопка, которая ничего не делает,
 * и рядом чужие названия — «Красногвардейский 2-к до 15», «Расселение,
 * центр», — которых человек никогда не заводил.
 *
 * Теперь источник один и живёт здесь. Второй каркас не может отстать,
 * потому что второго источника не существует.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * СЧЁТЧИКИ СЧИТАЮТСЯ, А НЕ ВПИСЫВАЮТСЯ. В файле навигации стояли «Сегодня 7»
 * и «Подборки 4»; человек, создавший агентство минуту назад, видел семёрку
 * и открывал пустой экран. Счётчик, который нечего считать, не рисуется
 * вовсе: ноль рядом с пунктом читается как поломка, а не как «пока пусто».
 */
export function useCabinetNav() {
  const workspace = useWorkspace()
  const now = useNow()

  const dueToday = callbacksDue(workspace, now).length + takenNotCalled(workspace).length

  const items: NavEntry[] = NAV.map((item) => {
    if (item.id === "today") return { ...item, count: dueToday || undefined }
    if (item.id === "collections") {
      return { ...item, count: workspace.collections.length || undefined }
    }
    return item
  })

  /**
   * Сохранённые поиски — свои, и у каждого есть адрес.
   *
   * Пока все ведут на выдачу без параметров: применение сохранённых условий
   * появится вместе с экраном «Сохранённые поиски» (`bZOeU`). Ссылка,
   * которая открывает выдачу, честнее кнопки, которая молчит.
   */
  const savedSearches: NavEntry[] = workspace.savedSearches.map((item) => ({
    id: item.id,
    label: item.name,
    to: "/search",
  }))

  /**
   * Поиски агентства — общие для всех сотрудников.
   *
   * Пока данные лежат в браузере одного человека, «общее для агентства»
   * существовать не может: чужой браузер этих поисков не увидит. Раздел
   * поэтому пуст, и это честно. Он наполнится вместе с сервером.
   */
  const agencySearches: NavEntry[] = []

  return { items, savedSearches, agencySearches }
}
