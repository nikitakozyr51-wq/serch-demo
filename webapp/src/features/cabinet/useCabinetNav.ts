import { NAV } from "@/cabinet-demo-nav"
import { useSession } from "@/features/auth"
import { callbacksDue, takenNotCalled, useNow, useWorkspace } from "@/features/workspace"
import type { NavEntry } from "./CabinetSidebar"

/**
 * Боковое меню кабинета: один источник на оба каркаса.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * **Из-за двух источников владелец сказал: «не могу нажать ни на один
 * сохранённый поиск в агентстве».** И был прав буквально. `CabinetShell`
 * брал поиски из работы агентства — у них есть адрес, и они были ссылками.
 * `AgencyShell` отдавал в тот же сайдбар константы из файла навигации,
 * у которых адреса нет вовсе; сайдбар в этом случае рисует `<button>`,
 * а обработчик ему никто не передавал. Кнопка, которая ничего не делает,
 * и рядом чужие названия — «Красногвардейский 2-к до 15», «Расселение,
 * центр», — которых человек никогда не заводил.
 *
 * Теперь источник один и живёт здесь. Второй каркас не может отстать,
 * потому что второго источника не существует.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * СЧЁТЧИКИ СЧИТАЮТСЯ, А НЕ ВПИСЫВАЮТСЯ. В файле навигации стояли «Сегодня 7»
 * и «Подборки 4»; человек, создавший агентство минуту назад, видел семёрку
 * и открывал пустой экран. Счётчик, который нечего считать, не рисуется
 * вовсе: ноль рядом с пунктом читается как поломка, а не как «пока пусто».
 */
/**
 * Тип возврата назван явно, а не выведен.
 *
 * `agencySearches` сегодня всегда `undefined` — раздела нет, пока нет
 * сервера, — и без объявления помощник сужал его до `undefined` навсегда.
 * Экраны, которые с ним работают, теряли из-за этого тип строки, а вернуть
 * раздел стало бы правкой в трёх файлах вместо одного.
 */
type CabinetNav = {
  items: NavEntry[]
  savedSearches: NavEntry[]
  agencySearches: NavEntry[] | undefined
}

/**
 * Разделы, которых у агента нет.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * «Агентство» — это сотрудники, дневные лимиты, журнал доступа и отчёты
 * по чужой работе. Всё это принадлежит руководителю, и агенту там нечего
 * ни смотреть, ни менять: правила доступа в базе его туда не пустят.
 *
 * Пункт при этом стоял у обоих, и это была не косметика. Агент нажимал
 * на него и получал либо пустоту, либо отказ базы — то есть продукт
 * обещал раздел, которого у этого человека нет. Обещание, которое нельзя
 * сдержать, хуже отсутствующего пункта: первое человек считает поломкой,
 * второе не замечает вовсе.
 *
 * Меню от этого становится четырёхпунктовым — так и нарисовано в обучении,
 * где у агента пять глав вместо шести.
 */
const OWNER_ONLY = new Set(["agency"])

export function useCabinetNav(): CabinetNav {
  const workspace = useWorkspace()
  const session = useSession()
  const now = useNow()

  const owner = session?.role !== "agent"
  const dueToday = callbacksDue(workspace, now).length + takenNotCalled(workspace).length

  const items: NavEntry[] = NAV.filter((item) => owner || !OWNER_ONLY.has(item.id)).map((item) => {
    if (item.id === "today") return { ...item, count: dueToday || undefined }
    if (item.id === "collections") {
      return { ...item, count: workspace.collections.length || undefined }
    }
    return item
  })

  /**
   * Сохранённые поиски — свои, и каждый открывает СВОИ условия.
   *
   * Раньше все вели на `/search` без параметров: пункт назывался «Невский,
   * 2-к до 12 млн», а открывал выдачу со случайными условиями. Экран
   * сохранённых поисков (`bZOeU`) с тех пор собран и умеет открывать поиск
   * по идентификатору — сайдбар делает ровно то же.
   */
  const savedSearches: NavEntry[] = workspace.savedSearches.map((item) => ({
    id: item.id,
    label: item.name,
    to: "/search",
    search: { saved: item.id },
  }))

  /**
   * Поиски агентства — общие для всех сотрудников.
   *
   * ═══════════════════════════════════════════════════════════════════════════
   *
   * Пока данные лежат в браузере одного человека, «общее для агентства»
   * существовать не может: чужой браузер этих поисков не увидит.
   *
   * Поэтому раздела НЕТ ВОВСЕ, а не «есть, но пуст». Разница описана
   * в контракте самого сайдбара: `[]` — заголовок стоит, поисков ещё нет
   * (кадр `uCehD`); `undefined` — раздела нет (кадр `EF9xj`). Здесь стоял
   * `[]`, и человек видел метку «ПОИСКИ АГЕНТСТВА» без единой строки под ней
   * на каждом экране кабинета — обещание раздела, наполнить который сегодня
   * нечем ничем. Второе состояние из файла при этом было недостижимо.
   */
  const agencySearches: NavEntry[] | undefined = undefined

  return { items, savedSearches, agencySearches }
}
