import { Navigate } from "@tanstack/react-router"
import type { ReactNode } from "react"

import { useSession } from "@/features/auth"
import { loginPath } from "./platform"

/**
 * Кабинет закрыт для тех, кто не вошёл.
 *
 * **Это не формальность, а часть продукта.** Кабинет показывает деньги
 * агентства, журнал доступа и телефоны собственников. Дверь, которая
 * открывается всем подряд, превращает демонстрацию системы в демонстрацию
 * картинок: человек не понимает, что вход вообще есть.
 *
 * **Куда ведёт.** На `/login`, а не на главную сайта: человек шёл в кабинет,
 * значит ему нужен вход, а не витрина. Возврат мгновенный и без сообщения —
 * сообщение «вы не авторизованы» ничего не добавляет к экрану входа,
 * на котором человек уже стоит.
 *
 * **Чего guard не делает.** Он не защищает данные: за ним нет сервера,
 * и всё, что показывает кабинет, лежит в той же странице. Это дверь,
 * а не замок, и притворяться замком она не должна.
 */
function CabinetGuard({ children }: { children: ReactNode }) {
  const session = useSession()

  // `returnTo` объявлен в маршруте входа обязательным параметром поиска,
  // поэтому передаётся явно. Пустое значение честнее выдуманного адреса:
  // куда человек шёл, знает он, а не дверь.
  // Вход выбирается по ширине экрана: на телефоне десктопный кадр входа
  // 1440 × 1024 нечитаем, и человек упирался в него вместо формы.
  if (!session) {
    return <Navigate to={loginPath()} search={{ returnTo: undefined }} replace />
  }

  return <>{children}</>
}

export { CabinetGuard }
