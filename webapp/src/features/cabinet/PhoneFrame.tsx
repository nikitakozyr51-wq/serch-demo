import { useRouterState } from "@tanstack/react-router"
import type { ReactNode } from "react"

import { cn } from "@/lib/utils"
import { useMobileFramed } from "./mobile-framed"

/**
 * Кадр телефона: рамка на стенде, полноэкранная страница на телефоне.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ ЭТОТ КОМПОНЕНТ ПОЯВИЛСЯ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Владелец: «Я открыл мобильную версию, даже в режиме инкогнито. Я не могу
 * там зарегистрировать агентство, потому что там сломан экран, он такой же
 * как на ПК, весь суженый.»
 *
 * Причина оказалась не в вёрстке отдельного экрана. **Все двадцать четыре
 * мобильных экрана были собраны как СТЕНДЫ**, а не как страницы: каждый
 * рисовал себя внутри жёсткой коробки `390 × 844` на сером фоне с полем 40.
 * Так удобно смотреть кадр рядом с макетом в обычном браузере — и ровно так
 * нельзя показывать человеку с телефона: на экране шириной 390 коробка 390
 * плюс поля 80 не помещается, страница получает горизонтальную прокрутку,
 * а вокруг содержимого стоит серая рамка.
 *
 * Десять файлов повторяли эту коробку копией. Теперь она одна и знает
 * разницу между стендом и продуктом.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * **Стенд узнаётся по адресу, а не по флагу.** Экраны сверки живут на
 * `/screen/…`, и адрес — это и есть то, что отличает стенд от продукта.
 * Второго источника правды тут заводить незачем; ровно так же устроено
 * правило `useOwnAgency`, которое на стенде показывает замеренные данные.
 *
 * На стенде кадр обведён волосяной линией и стоит по центру серого поля —
 * так его видно целиком рядом с макетом. В продукте это `h-svh w-full`:
 * ни рамки, ни полей, ни серого фона.
 */
/**
 * Заливка кадра — замер, а не украшение.
 *
 * Экран кабинета идёт `bg`; экран блокировки телефона — графит; два кадра
 * массовых действий нарисованы вовсе без собственной заливки, там весь кадр
 * и есть затемнение поверх пустоты.
 */
const SURFACE = {
  bg: "bg-bg",
  dark: "bg-fg",
  none: "",
} as const

function PhoneFrame({
  slot,
  surface = "bg",
  children,
}: {
  /** Имя узла для проверок: `mobile-screen`, `mobile-auth-screen`, … */
  slot: string
  surface?: keyof typeof SURFACE
  children: ReactNode
}) {
  const pathname = useRouterState({ select: (state) => state.location.pathname })
  const stand = pathname.startsWith("/screen/")
  const framed = useMobileFramed()

  // `relative` обязателен: лист снизу лежит абсолютом поверх экрана,
  // а не в потоке.
  const shell = cn("relative flex flex-col overflow-hidden", SURFACE[surface])

  if (!stand) {
    // Внутри постоянного каркаса высоту задаёт он, а не экран: два `h-svh`
    // подряд вытолкнули бы нижнюю навигацию за нижний край окна.
    return (
      <div
        data-slot={slot}
        className={cn(shell, "w-full", framed ? "min-h-0 flex-1" : "h-svh")}
      >
        {children}
      </div>
    )
  }

  return (
    <div className="flex min-h-svh w-full items-start justify-center bg-line-1 p-10">
      <div
        data-slot={slot}
        className={cn(
          shell,
          "h-[844px] w-[390px]",
          "outline-solid outline-1 -outline-offset-1 outline-line-2",
        )}
      >
        {children}
      </div>
    </div>
  )
}

export { PhoneFrame }
