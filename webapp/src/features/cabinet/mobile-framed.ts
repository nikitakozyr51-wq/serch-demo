import { createContext, useContext } from "react"

/**
 * Экран рисуется внутри постоянного мобильного каркаса.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Нижняя навигация была вмонтирована в КАЖДЫЙ мобильный экран, и при касании
 * вкладки умирала вместе с ним: пять главных дверей продукта исчезали и
 * появлялись заново на каждом переходе. На телефоне это заметнее, чем
 * на компьютере, — навигация занимает низ экрана и мигает прямо под пальцем.
 *
 * Теперь навигацию держит каркас на маршруте, а экран отдаёт только тело.
 * Признак передаётся контекстом, а не свойством: иначе его пришлось бы
 * прокидывать через пять вызовов и не забыть на шестом. Каркас знает, что
 * он каркас; экраны об этом не думают.
 *
 * По умолчанию `false` — экран сам себе корень. Так живут внутренние экраны
 * ветки объекта и листы, которым навигация не положена вовсе.
 */
const MobileFramedContext = createContext(false)

/** Внутри ли постоянного каркаса. Меняет корень экрана и убирает вторую навигацию. */
function useMobileFramed(): boolean {
  return useContext(MobileFramedContext)
}

export { MobileFramedContext, useMobileFramed }
