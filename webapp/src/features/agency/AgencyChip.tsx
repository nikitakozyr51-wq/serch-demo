import { StateChip, type StateTone } from "@/components/controls/StateChip"

/**
 * Бейдж состояния в таблицах агентства.
 *
 * **Это обёртка над общим `StateChip`, а не своя фигура.** Точка и слово
 * жили в продукте тремя копиями: здесь, в строке выдачи и в списке возвратов.
 * Копии успели разойтись — у этой точка «законченного» состояния шла
 * `text-dense`, а замер показывает `text-3`. Разойтись им было нечем,
 * кроме как по недосмотру: фигура одна, смысл один.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ЧТО ОСТАЛОСЬ СВОИМ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Словарь тонов. Общий чип знает про цвет, а таблица агентства — про смысл:
 *
 *   calm       обычное состояние, ничего не происходит
 *   attention  идёт процесс или что-то требует взгляда
 *   done       состояние закончилось, действий больше нет
 *
 * Набор состояний у каждой таблицы свой, и смешивать их нельзя: у объекта
 * «В работе», «Отказ», «Раскрыт»; у номера в реестре «Скрыт», «На удалении»,
 * «Удалён»; у сотрудника «Активен» и «Отключён».
 *
 * **Подложки нет** (передача 05.08.2026, раздел 1) — и не появится: плашка
 * это поверхность, а состояние не поверхность, оно ничего не содержит
 * и никуда не ведёт. В таблице на восемь колонок восемь плашек в колонке
 * статуса читались восемью кнопками, которых там нет.
 */
type ChipTone = "calm" | "attention" | "done"

const TONE = {
  calm: "ok",
  attention: "warn",
  done: "quiet",
} as const satisfies Record<ChipTone, StateTone>

function AgencyChip({ label, tone = "calm" }: { label: string; tone?: ChipTone }) {
  return (
    <StateChip tone={TONE[tone]} slot="agency-chip">
      {label}
    </StateChip>
  )
}

export { AgencyChip }
export type { ChipTone as AgencyChipTone }
