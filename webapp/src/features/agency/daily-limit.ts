import { DISCLOSURE_PRICE } from "@/features/auth"
import { groupDigits } from "@/features/listings"

/**
 * Дневной лимит раскрытий: ступени и то, как они называются.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Живёт отдельно от окна, и не по прихоти правила о быстрой перезагрузке.
 * Эти три ступени — правило продукта, а не свойство одного диалога: те же
 * числа стоят чипами в карточке сотрудника (`t6b58y`), в правилах агентства
 * (`cNIZP`) и в приглашении (`B8Irc`). Пока они лежали внутри окна, четвёртое
 * место неизбежно завело бы четвёртую копию — и однажды одна из них
 * разошлась бы с остальными.
 */

/**
 * Три готовых ответа на вопрос «сколько раскрытий в день».
 *
 * Ровно те же три, что стоят чипами в карточке сотрудника (`t6b58y`) и
 * в правилах агентства (`cNIZP`): продукт не знает четвёртого лимита, и
 * поле для ввода произвольного числа здесь было бы новым правилом, а не
 * новым окном.
 */
export const DAILY_LIMITS: { label: string; note: string; value: number | null }[] = [
  { label: "5 в сутки", note: "умолчание для новых сотрудников", value: 5 },
  { label: "25 в сутки", note: "для тех, кто много звонит", value: 25 },
  { label: "Без лимита", note: "только руководителю", value: null },
]

/** «5 в сутки» или «без лимита» — тем же языком, что в таблице сотрудников. */
export function dailyLimitWord(limit: number | null): string {
  return limit === null ? "без лимита" : `${limit} в сутки`
}

/**
 * Потолок дня в рублях.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Лимит — это не «сколько строк откроется», а сколько чужих денег человек
 * может потратить за сутки. Раскрытие стоит 199 ₽ со счёта агентства, и
 * разница между «5 в сутки» и «25 в сутки» — это 995 ₽ против 4 975 ₽
 * в день. Руководитель обязан прочитать это число до нажатия, а не вывести
 * его в уме, поэтому строка пересчитывается прямо под выбором.
 *
 * Цена берётся из слоя денег (`DISCLOSURE_PRICE`), а не пишется здесь
 * копией: 199 в двух местах разъедутся при первой же смене прайса.
 */
export function dailyLimitCost(limit: number | null): string {
  if (limit === null) return "Без лимита потолка дня нет."
  return `Потолок дня — ${groupDigits(limit * DISCLOSURE_PRICE)} ₽ со счёта агентства.`
}

