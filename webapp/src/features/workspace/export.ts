/**
 * Выгрузки и документы — по-настоящему, прямо в браузере.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Владелец сказал: кнопки должны быть включены и работать везде. Он прав, и
 * прежнее объяснение «нужен сервер» верно было только наполовину.
 *
 * Сервер нужен, чтобы ОТПРАВИТЬ файл другому человеку или подписать его
 * печатью. Но чтобы СФОРМИРОВАТЬ файл из данных, которые уже лежат перед
 * глазами, сервер не нужен вовсе: браузер умеет собрать текст и отдать его
 * на диск. Журнал доступа, согласия, отказы, выписка баланса, отчёт по
 * эффективности, счёт и акт — всё это складывается из журналов агентства.
 *
 * Поэтому здесь нет ни одной заглушки: каждая кнопка выгрузки отдаёт
 * настоящий файл с настоящими данными этого агентства.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * ФОРМАТ. CSV с разделителем «точка с запятой» и BOM в начале: Excel в
 * русской локали открывает такой файл двойным щелчком и не превращает
 * «24.07» в дату, а «8 610» — в число с потерянным пробелом. Запятая как
 * разделитель ломает и то, и другое.
 *
 * ТЕЛЕФОНОВ В ВЫГРУЗКАХ НЕТ. Это правило продукта, а не упрощение: «выгрузка
 * номеров пачкой недоступна никому, включая руководителя». Файл, который
 * можно унести с собой, не должен уносить контакты собственников.
 */

/** Экранирование поля CSV: точка с запятой и кавычки внутри значения. */
function cell(value: string | number): string {
  const text = String(value)
  return /[";\n]/.test(text) ? `"${text.replaceAll('"', '""')}"` : text
}

/**
 * Отдать файл на диск.
 *
 * Ссылка создаётся и убирается сразу: узел, оставшийся в документе, начинает
 * ловить фокус клавиатурой и читается диктором как пустая ссылка.
 */
export function download(name: string, content: string, mime = "text/csv;charset=utf-8") {
  // BOM обязателен: без него Excel читает файл как однобайтовый и показывает
  // кириллицу крокозябрами. Это не суеверие, это поведение Excel по сей день.
  // Записан экранированием, а не самим символом: невидимый знак в исходнике
  // выглядит как пустое место, и следующая правка стёрла бы его случайно.
  const blob = new Blob([`\uFEFF${content}`], { type: mime })
  const url = URL.createObjectURL(blob)
  const link = document.createElement("a")
  link.href = url
  link.download = name
  document.body.append(link)
  link.click()
  link.remove()
  // Освобождать адрес сразу нельзя: часть браузеров не успевает начать
  // скачивание. Минуты хватает с большим запасом.
  window.setTimeout(() => URL.revokeObjectURL(url), 60_000)
}

/** Собрать CSV из шапки и строк. */
export function csv(head: string[], rows: Array<Array<string | number>>): string {
  return [head, ...rows].map((row) => row.map(cell).join(";")).join("\r\n")
}

/**
 * Имя файла с датой: «журнал-доступа-2026-08-06.csv».
 *
 * Дата в имени — не украшение: агентство выгружает журнал по запросу
 * проверяющего, и два файла без дат в одной папке через неделю неразличимы.
 */
export function fileName(base: string, at: number, extension = "csv"): string {
  const date = new Date(at)
  const two = (value: number) => String(value).padStart(2, "0")
  return `${base}-${date.getFullYear()}-${two(date.getMonth() + 1)}-${two(date.getDate())}.${extension}`
}

/**
 * Документ для бухгалтерии: счёт, акт или счёт-фактура.
 *
 * Отдаётся текстом, а не PDF: PDF без подписи и печати всё равно не документ,
 * а текст открывается везде и его видно целиком. Когда появится сервер,
 * подписанный PDF придёт оттуда — а до тех пор бухгалтер получает то же
 * содержимое, только простым файлом.
 */
export function accountingDocument(input: {
  kind: string
  number: string
  at: number
  agency: string
  lines: Array<[string, string]>
  total: string
}): string {
  const date = new Date(input.at)
  const two = (value: number) => String(value).padStart(2, "0")
  const when = `${two(date.getDate())}.${two(date.getMonth() + 1)}.${date.getFullYear()}`

  return [
    `${input.kind} № ${input.number} от ${when}`,
    "",
    `Агентство: ${input.agency}`,
    "Исполнитель: ООО «Сёрчь», оператор персональных данных,",
    "уведомление в Роскомнадзор № 78-19-004182",
    "",
    ...input.lines.map(([what, sum]) => `${what.padEnd(56, " ")}${sum}`),
    "",
    `ИТОГО${" ".repeat(51)}${input.total}`,
    "",
    "Документ сформирован кабинетом и не содержит телефонов собственников.",
  ].join("\r\n")
}
