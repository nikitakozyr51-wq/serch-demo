/**
 * Обучение первого входа: шесть глав, двадцать шагов.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Тексты сняты с кадров `ОБУЧЕНИЕ · Глава N · Шаг M` — до слова, а не
 * пересказаны. Пересказ здесь дороже обычного: обучение это единственное
 * место продукта, где текст и есть работа.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ПОЧЕМУ ГЛАВЫ, А НЕ СПЛОШНАЯ ЛЕНТА
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Владелец просил разжевать подробно: «мне всё равно, что там может быть
 * много текста». Двадцать окон подряд без передышки пролистывают целиком —
 * и тогда подробность не помогла, а помешала.
 *
 * Поэтому подробность даётся структурой: человек видит «глава 2 из 6 ·
 * шаг 3 из 4», может выйти и вернуться на том же шаге, может пропустить
 * главу целиком. Это не урезание объёма — это то, что делает объём
 * проходимым.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ЧТО ЗНАЧИТ `target`
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Селектор элемента, о котором шаг говорит. Он подсвечивается: остаётся
 * в полном свете, всё вокруг затемняется. Селектор ищется по `data-slot` —
 * постоянной метке, а не по классу оформления: тур, привязанный к классам,
 * отвалится при первой правке вида и сделает это молча.
 *
 * `target` пуст у обложек глав и у завершения: им не на что показывать,
 * и окно встаёт по центру.
 */

/** Куда встаёт окно относительно подсвеченного: сторона со стрелкой. */
type TourSide = "right" | "left" | "top" | "bottom" | "center"

type TourStep = {
  /** Глава, к которой шаг принадлежит. Обложки — шаг 0 своей главы. */
  chapter: number
  /** Заголовок окна. */
  title: string
  /** Объяснение в две-четыре фразы. */
  text: string
  /** Что подсветить. Пусто — окно по центру, подсвечивать нечего. */
  target?: string
  side?: TourSide
  /** Куда увести перед показом шага. Пусто — остаёмся, где стоим. */
  at?: string
  /** Подпись главного действия. По умолчанию «Дальше». */
  action?: string
}

