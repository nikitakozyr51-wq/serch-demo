import { Outlet, useRouterState } from '@tanstack/react-router'

import { usePlatformRoute } from '@/features/cabinet'
import { Notices } from '@/platform/notify'

/**
 * Корень приложения.
 *
 * Единственное, что здесь живёт, — правило «кабинет открывается тем экраном,
 * который подходит устройству». Оно обязано стоять выше всех экранов сразу:
 * человек приходит на произвольный адрес по ссылке, и решать, показать ему
 * десктопный кадр или мобильный, нужно до того, как экран отрисуется.
 *
 * До этого правила мобильного кабинета фактически не существовало. Он был
 * собран целиком — двадцать четыре экрана, — но попасть в него с телефона
 * было нечем: человек открывал ссылку и получал десктопный кабинет шириной
 * 1440 в окне 390.
 */
export function RootLayout() {
  usePlatformRoute()

  /**
   * Смена экрана: проявление 160 мс.
   *
   * ═══════════════════════════════════════════════════════════════════════
   *
   * Переход был мгновенным, и владелец описал результат как «нет никаких
   * анимаций». Мгновенная подмена кадра действительно читается как перезагрузка
   * страницы: глаз не успевает связать то, что было, с тем, что стало.
   *
   * Ключ — адрес экрана. React перерисовывает поддерево заново при каждой
   * смене адреса, и анимация запускается с начала. Поисковая строка в ключ
   * НЕ входит намеренно: открытие карточки объекта меняет `?at=`, и экран
   * мигал бы на каждом переходе стрелками между объектами.
   *
   * Двигается только прозрачность. Сдвиг здесь был бы дороже: агент делает
   * тридцать-пятьдесят переходов за смену, и каждый лишний пиксель движения
   * умножается на это число.
   */
  const pathname = useRouterState({ select: (state) => state.location.pathname })

  // Обёртка обычная, а не `display: contents`: у безкоробочного элемента
  // прозрачности не бывает, и анимация к нему просто не применилась бы.
  // Высоту она не навязывает — экраны задают свою (`h-svh`) сами.
  return (
    <>
      <div key={pathname} className="screen-in">
        <Outlet />
      </div>
      {/* Полка сообщений вне ключа: она обязана пережить смену экрана.
          Внутри она исчезала бы вместе с ним — «Скопировано» гасло бы
          ровно в тот момент, когда прозвон переходит к следующему объекту. */}
      <Notices />
    </>
  )
}
