import { Outlet } from '@tanstack/react-router'
import { MotionConfig } from 'motion/react'

import { usePlatformRoute, useOverlayOpen } from '@/features/cabinet'
import { TourOverlay } from '@/features/tour'
import { Notices } from '@/platform/notify'

/**
 * Корень приложения.
 *
 * Единственное, что здесь живёт, — правило «кабинет открывается тем экраном,
 * который подходит устройству». Оно обязано стоять выше всех экранов сразу:
 * человек приходит на произвольный адрес по ссылке, и решать, показать ему
 * десктопный кадр или мобильный, нужно до того, как экран отрисуется.
 *
 * До этого правила мобильного кабинета фактически не существовало. Он был
 * собран целиком — двадцать четыре экрана, — но попасть в него с телефона
 * было нечем: человек открывал ссылку и получал десктопный кабинет шириной
 * 1440 в окне 390.
 */
export function RootLayout() {
  usePlatformRoute()

  /**
   * Обучение живёт в корне, а не в каркасе кабинета.
   *
   * ═══════════════════════════════════════════════════════════════════════
   *
   * Сначала оно стояло рядом с палитрой и картой клавиш — и пропадало
   * на «Прозвоне»: тот экран полноэкранный и каркаса кабинета не несёт
   * вовсе. Обучение обрывалось ровно на четырнадцатом шаге, который про
   * прозвон и рассказывает.
   *
   * Здесь же оно переживает и смену экрана: шаги уводят человека по
   * разделам, а окно обязано ехать вместе с ним, а не пересоздаваться
   * на каждом адресе.
   */
  const overlayOpen = useOverlayOpen()

  /*
    ЗДЕСЬ БОЛЬШЕ НЕТ КЛЮЧА ПО АДРЕСУ — И ЭТО САМАЯ ВАЖНАЯ СТРОКА ФАЙЛА.

    ═══════════════════════════════════════════════════════════════════════

    Стояло `<div key={pathname} className="screen-in">` вокруг `Outlet`.
    Задумано было как проявление экрана, а работало иначе, и сразу двумя
    способами плохо.

    **Первое: смена ключа сносит ВСЁ поддерево.** Не «перезапускает
    анимацию», а уничтожает и строит заново — вместе с шапкой, боковым
    меню, счётчиком денег и палитрой, которые лежат ниже. Это и есть
    «весь сайт слишком дёрганый». Поднять каркас на маршрут и оставить
    здесь ключ — значит не сделать ничего: ключ снёс бы и новый каркас.
    Проверка «каркас переживает смену раздела» именно это и поймала.

    **Второе: проявление играло не на том экране.** Адрес меняется
    в НАЧАЛЕ навигации, а экран приезжает позже — после загрузки своего
    куска кода. Ключ успевал смениться раньше, чем появлялся новый экран,
    поэтому 200 мс проявления доставались уходящему, а входящий подменялся
    вовсе без анимации.

    Проявление переехало внутрь каркаса — на тело, а не на весь кабинет,
    и ключом ему служит отрисованный маршрут, а не адрес. См.
    `features/cabinet/CabinetFrame.tsx`.
  */
  /**
   * Настройка «меньше движения» — одна на весь продукт, и она автоматическая.
   *
   * ═══════════════════════════════════════════════════════════════════════
   *
   * `reducedMotion="user"` заставляет библиотеку выбросить из КАЖДОЙ анимации
   * сдвиг, масштаб и поворот, оставив прозрачность и цвет. Это ровно то,
   * что нужно: человек, которому от движения делается плохо, всё равно видит,
   * что окно появилось, — просто оно не едет.
   *
   * Правило стоит здесь, а не на экранах, потому что иначе оно обязано
   * стоять на каждом из них. Один пропущенный экран — и обещание нарушено;
   * а обещание доступности, работающее через раз, хуже отсутствующего.
   *
   * Общий ковёр в `index.css` при этом остаётся: он гасит CSS-переходы,
   * до которых библиотека не дотягивается.
   */
  return (
    <MotionConfig reducedMotion="user">
      <Outlet />
      {/* Полка сообщений вне ключа: она обязана пережить смену экрана.
          Внутри она исчезала бы вместе с ним — «Скопировано» гасло бы
          ровно в тот момент, когда прозвон переходит к следующему объекту. */}
      {/* Обучение молчит, пока открыто окно: палитра, карта клавиш или
          диалог уже держат внимание, и второй слой поверх них — помеха.
          Вне ключа адреса: шаги уводят по разделам, и окно едет с человеком. */}
      <TourOverlay blocked={overlayOpen} />

      <Notices />
    </MotionConfig>
  )
}
