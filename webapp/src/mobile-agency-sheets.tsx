import { useState } from "react"

import { Button } from "@/components/controls/Button"
import { Typography } from "@/components/typography"
import { MobileField, MobileOverlaySheet, SheetChoiceRow } from "@/mobile-sheet-parts"

/**
 * Четыре листа руководителя: отключить сотрудника, передать роль, реквизиты,
 * удалить агентство.
 *
 * `GIv2U` · `iWj2M` · `TIJHR` · `hnnq8`.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ЭТО ТЕЛЕФОННЫЕ БЛИЗНЕЦЫ УЖЕ СОБРАННЫХ ОКОН, И ТЕКСТ У НИХ ОБЩИЙ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Три из четырёх собраны на компьютере в `features/agency/AgencyDialogs.tsx`:
 * `cXuHY` реквизиты, `B3hBi` передача роли, `d7JoII` удаление агентства.
 * Слова, правила проверки и порядок кнопок взяты оттуда слово в слово —
 * решать второй раз то, что уже решено, значит однажды разойтись с ним.
 * Отличается ФОРМА: лист снизу вместо окна по центру, кнопки во всю ширину
 * вместо ряда справа, строки выбора 60 вместо 56.
 *
 * **Что нужно сделать дальше (не в этом файле).** Пока текст скопирован,
 * а не разделён: правка формулировки стоит двух правок. Слова этих трёх окон
 * обязаны переехать в `features/agency/agency-dialog-text.ts` и раздаваться
 * оттуда обеим платформам через `features/agency/index.ts`. Оба файла общие,
 * и правятся они не отсюда.
 *
 * У четвёртого, «Отключить сотрудника», собранного близнеца нет: на компьютере
 * в `agency-staff-screen.tsx` кнопка «Отключить доступ» только называет
 * действие и честно на этом останавливается, потому что подтверждения там
 * не нарисовано. Здесь оно нарисовано — значит здесь оно и появляется.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ПОЧЕМУ У ВСЕХ ЧЕТЫРЁХ ЕСТЬ ПОДТВЕРЖДЕНИЕ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Каждое из этих действий либо необратимо, либо меняет ЧУЖИЕ экраны. Отмены
 * у них нет и быть не может: прежние значения не сохраняются. Поэтому лист
 * называет последствие РАНЬШЕ, чем показывает кнопку, — и называет числом
 * и именами, а не словом «некоторые».
 */

/**
 * МОБАЙЛ · Отключить сотрудника (`GIv2U`).
 *
 * **Второе предложение важнее первого.** Руководитель, отключающий человека,
 * боится потерять его работу: раскрытые контакты, за которые агентство
 * заплатило, и историю звонков. Лист отвечает на этот страх до кнопки —
 * работа остаётся агентству, пропадает только доступ.
 *
 * **Имя стоит через точку, а не в винительном падеже.** В кадре написано
 * «Отключить Гусева Петра?» — склонённой фамилией живого человека. Склонять
 * произвольные имена продукт не умеет, а «Отключить Гусев Пётр?» хуже
 * отсутствия имени. Точка-разделитель — приём, которым в этом продукте уже
 * решён тот же вопрос: «Дневной лимит · Гусев Пётр».
 */
function DisableStaffSheet({
  person,
  position,
  onDisable,
  onClose,
}: {
  /** Кого отключают. Имя стоит в заголовке: отключают не «сотрудника вообще». */
  person: string
  position?: "fixed" | "absolute"
  onDisable: () => void
  onClose: () => void
}) {
  return (
    <MobileOverlaySheet
      label="Отключить доступ сотрудника"
      title={`Отключить доступ · ${person}?`}
      text="Доступ пропадёт сразу. Объекты, раскрытые контакты и история звонков остаются агентству."
      position={position}
      onClose={onClose}
      actions={
        <>
          {/*
            Заливка цвета ошибки, а не акцента. Акцент означает «сейчас
            спишутся деньги» и зовёт нажать; здесь красный означает «обратно
            не будет» и предупреждает. Один красный на два противоположных
            смысла научил бы не замечать оба.
          */}
          <Button
            variant="danger"
            size="lg"
            block
            // Порта «снять доступ» в слое входа нет ни на одной платформе:
            // на компьютере кнопка «Отключить доступ» тоже только называет
            // действие. Атрибут говорит, что случится, и не врёт о записи
            // на сервер, которой не происходит.
            data-action="Отключает сотрудника: доступ пропадает, объекты и история остаются агентству"
            onClick={onDisable}
          >
            Отключить
          </Button>
          <Button variant="quiet" size="lg" block onClick={onClose}>
            Отмена
          </Button>
        </>
      }
    />
  )
}

/**
 * МОБАЙЛ · Передать роль (`iWj2M`).
 *
 * Близнец окна `B3hBi`. **Роль ответственного за данные неразрывна
 * с руководительской**, потому что ролей в системе ровно две. Тот, кому
 * передали, становится руководителем; передавший — агентом. Об этом сказано
 * в самом листе, а не в справке: человек должен узнать это до нажатия.
 *
 * Сноска внизу называет то, чего человек не проверит сам: из интерфейса
 * это необратимо, и вернуть роль сможет только новый руководитель.
 *
 * **Подпись под именем говорит роль и лимит, а не выработку.** В кадре
 * стоит «агент · 52 раскрытия · в агентстве с апреля», в собранном окне
 * на компьютере — «агент · лимит 5 в сутки». Взято второе: подпись
 * в двух платформах обязана отвечать на один и тот же вопрос, иначе
 * руководитель, выбравший на компьютере по лимиту, на телефоне выберет
 * по выработке и получит другого человека.
 */
function TransferOwnerSheet({
  ownerName,
  people,
  position,
  onTransfer,
  onClose,
}: {
  /** Кто ответственный сейчас. */
  ownerName: string
  /** Кому можно передать: все, кроме себя. */
  people: { id: string; name: string; note: string }[]
  position?: "fixed" | "absolute"
  onTransfer: (personId: string) => void
  onClose: () => void
}) {
  const [chosen, setChosen] = useState<string | null>(people[0]?.id ?? null)

  return (
    <MobileOverlaySheet
      label="Передать роль"
      title="Передать роль ответственного за данные"
      text={`Сейчас ответственный — ${ownerName}: он подписывает согласия и отвечает на запросы собственников. Ролей в системе ровно две, поэтому роль неразрывна с руководительской: тот, кому вы её передадите, станет руководителем агентства, а вы — агентом.`}
      rhythm="medium"
      position={position}
      onClose={onClose}
      actions={
        <>
          <Button
            variant="primary"
            size="lg"
            block
            disabled={chosen === null}
            onClick={() => chosen !== null && onTransfer(chosen)}
          >
            Передать роль
          </Button>
          <Button variant="quiet" size="lg" block onClick={onClose}>
            Отмена
          </Button>
        </>
      }
    >
      {people.length === 0 ? (
        <Typography variant="denseText" tone="dense">
          Передать роль некому: в агентстве вы один. Сначала пригласите сотрудника.
        </Typography>
      ) : (
        <div
          role="radiogroup"
          aria-label="Кому передать роль"
          className="flex w-full flex-col gap-2"
        >
          {people.map((person) => (
            <SheetChoiceRow
              key={person.id}
              label={person.name}
              note={person.note}
              selected={person.id === chosen}
              onSelect={() => setChosen(person.id)}
            />
          ))}
        </div>
      )}

      <Typography variant="metaText" tone="dense">
        Из интерфейса это необратимо. Вернуть роль сможет только новый
        руководитель или поддержка по письму с реквизитами юрлица.
      </Typography>
    </MobileOverlaySheet>
  )
}

/**
 * МОБАЙЛ · Реквизиты агентства (`TIJHR`).
 *
 * Близнец окна `cXuHY`. Три поля: название, ИНН, юридический адрес — каждое
 * с подсказкой о том, куда это попадёт.
 *
 * **Менять их задним числом нельзя, и об этом сказано в самом листе.**
 * Документы за закрытые месяцы остаются с прежними данными: счёт, который
 * бухгалтер уже оплатил, не может изменить получателя.
 *
 * Единственный из восьми листов, где кнопка бывает выключена: пустое название
 * или пустой ИНН делают счёт невыставимым, и сохранять такое значит
 * откладывать отказ на потом. Правило взято у собранного окна.
 */
function RequisitesSheet({
  legalName,
  inn,
  legalAddress,
  position,
  onSave,
  onClose,
}: {
  legalName: string
  inn: string
  legalAddress: string
  position?: "fixed" | "absolute"
  onSave: (next: { legalName: string; inn: string; legalAddress: string }) => void
  onClose: () => void
}) {
  const [name, setName] = useState(legalName)
  const [tax, setTax] = useState(inn)
  const [address, setAddress] = useState(legalAddress)

  return (
    <MobileOverlaySheet
      label="Реквизиты агентства"
      title="Реквизиты агентства"
      text="Они печатаются в счёте, акте и счёте-фактуре. Менять их задним числом нельзя: документы за закрытые месяцы останутся с прежними данными."
      rhythm="medium"
      position={position}
      onClose={onClose}
      actions={
        <>
          <Button
            variant="primary"
            size="lg"
            block
            disabled={name.trim() === "" || tax.trim() === ""}
            onClick={() =>
              onSave({
                legalName: name.trim(),
                inn: tax.trim(),
                legalAddress: address.trim(),
              })
            }
          >
            Сохранить реквизиты
          </Button>
          <Button variant="quiet" size="lg" block onClick={onClose}>
            Отмена
          </Button>
        </>
      }
    >
      <MobileField
        label="НАЗВАНИЕ АГЕНТСТВА"
        hint="как в ЕГРЮЛ, оно попадёт в счёт и акт"
        value={name}
        onChange={(event) => setName(event.target.value)}
      />
      {/*
        Клавиатура числовая, но тип остаётся текстовым: `type="number"`
        роняет ведущий ноль и позволяет ввести знак минуса, а ИНН — это
        строка цифр, а не число, которым что-то считают.
      */}
      <MobileField
        label="ИНН"
        hint="проверим в ЕГРЮЛ автоматически"
        inputMode="numeric"
        value={tax}
        onChange={(event) => setTax(event.target.value)}
      />
      <MobileField
        label="ЮРИДИЧЕСКИЙ АДРЕС"
        hint="адрес из выписки, для счетов и закрывающих"
        value={address}
        onChange={(event) => setAddress(event.target.value)}
      />

      <Typography variant="metaText" tone="dense">
        Название юрлица и ИНН сверяются с ЕГРЮЛ при сохранении. Если не
        сходится — счёт не выставится, и это защита вас, а не формальность.
      </Typography>
    </MobileOverlaySheet>
  )
}

/**
 * МОБАЙЛ · Удалить агентство (`hnnq8`).
 *
 * Близнец окна `d7JoII` — самое необратимое действие продукта. Лист
 * перечисляет всё, что пропадёт, включая то, о чём человек не подумает:
 * ссылки на подборки у клиентов перестанут открываться. Клиент об этом
 * не узнает — он просто увидит, что страница не открывается.
 *
 * **Текст взят у собранного окна целиком, хотя в кадре он короче.** В `hnnq8`
 * написано «Поиски, подборки и ссылки у клиентов перестают работать»; окно
 * на компьютере говорит то же самое, но называет, что именно удаляется,
 * а что перестаёт открываться. Разница между «перестало работать» и «удалено»
 * — это разница между «подождём» и «уже нечего ждать», и терять её на телефоне
 * нельзя. Лист от этого выше на строку.
 */
function DeleteAgencySheet({
  agency,
  position,
  onRequest,
  onClose,
}: {
  agency: string
  position?: "fixed" | "absolute"
  onRequest: () => void
  onClose: () => void
}) {
  return (
    <MobileOverlaySheet
      label="Удалить агентство"
      title={`Удалить агентство «${agency}»?`}
      text="Доступ пропадёт у всех сотрудников сразу. Сохранённые поиски и подборки удаляются, ссылки на подборки у клиентов перестают открываться. Остаток счёта возвращается на счёт юрлица. Отменить нельзя."
      position={position}
      onClose={onClose}
      actions={
        <>
          {/*
            Обводка без заливки — замер `hnnq8/U5Tpd`: `stroke #a7463e`
            толщиной 1, заливки нет, подпись тем же цветом. Отличается от
            отключения сотрудника (`GIv2U/U5Tpd`, залито сплошь) намеренно:
            отключение откатывается приглашением обратно, удаление агентства
            не откатывается ничем, и мишени у него быть не должно.
          */}
          <Button variant="irreversible" size="lg" block onClick={onRequest}>
            Удалить агентство
          </Button>
          <Button variant="quiet" size="lg" block onClick={onClose}>
            Отмена
          </Button>
        </>
      }
    />
  )
}

export { DeleteAgencySheet, DisableStaffSheet, RequisitesSheet, TransferOwnerSheet }
