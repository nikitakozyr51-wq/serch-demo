/**
 * Отметка о вынужденной перезагрузке из-за устаревшего куска кода.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Экраны кабинета грузятся отдельными кусками. Когда демонстрацию выкладывают
 * заново, пока вкладка открыта, имена кусков меняются: браузер просит файл,
 * которого больше нет, GitHub Pages отдаёт `404.html`, и попытка выполнить
 * HTML как код кончается ошибкой вместо экрана.
 *
 * Лечится это только перезагрузкой — старого куска не существует, а новый
 * лежит по новому имени в свежем `index.html`. Отметка нужна, чтобы
 * перезагрузка случилась РОВНО ОДИН РАЗ: если новая версия падает по другой
 * причине, вкладка иначе крутилась бы в цикле «упал — перезагрузился — упал»,
 * и человек не увидел бы даже сообщения об ошибке.
 *
 * Живёт в `sessionStorage`, а не в переменной: переменная умирает вместе
 * со страницей, и цикл бы не оборвался. И не в `localStorage`: отметка
 * принадлежит этой вкладке и этому заходу, а не компьютеру навсегда.
 *
 * Лежит отдельным файлом от компонентов, потому что горячая замена модулей
 * в разработке работает только у файлов, экспортирующих одни компоненты.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * «РОВНО ОДИН РАЗ» БЫЛО ОБЕЩАНИЕМ, А НЕ ФАКТОМ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Первая редакция хранила единицу и стирала её при старте приложения:
 * «дошли до `main.tsx` — значит куски на месте». Это неверное рассуждение,
 * и оно стоило ровно того цикла, который отметка была обязана оборвать.
 * До `main.tsx` доезжает ВХОДНОЙ кусок; куски экранов к этому моменту ещё
 * никто не просил. Кусок экрана, который не приходит НИКОГДА, давал цепочку
 *
 *     загрузка → `main.tsx` стирает отметку → кусок не пришёл →
 *     перезагрузка → загрузка → отметка снова стёрта → …
 *
 * то есть вкладку, которая перезагружается вечно. Поймала это перепись
 * мобильного кабинета: экран `/m/saved-searches` восемь секунд не показывал
 * НИ ОДНОГО узла продукта — не потому, что он пустой, а потому, что страница
 * не доживала до отрисовки. Руками тот же адрес открывался нормально: там
 * куски уже лежали в кэше браузера и падать было нечему.
 *
 * Поэтому отметка теперь хранит ВРЕМЯ перезагрузки, а не факт. Время нельзя
 * «сбросить старт приложения»: оно истекает само и только само. Пока оно
 * свежее, второй перезагрузки не будет — будет честный экран с текстом.
 */

/**
 * Ключ отметки. Имя сменилось вместе со смыслом: раньше в нём лежала единица
 * «уже перезагружались», теперь — время перезагрузки. Старое имя оставлять
 * нельзя: во вкладках, открытых до этой правки, под ним лежит `"1"`, и новый
 * код прочитал бы его как «время ноль», то есть как отметку тридцатилетней
 * давности.
 */
const KEY = "serch.chunk-reloaded-at"

/**
 * Сколько времени перезагрузка считается «только что случившейся».
 *
 * Окно обязано с запасом накрывать один полный круг «перезагрузились —
 * и снова не доехало»: это загрузка всего приложения заново, секунды,
 * а не миллисекунды. И обязано быть заметно короче промежутка между двумя
 * выкладками демонстрации, иначе вторая выкладка за минуту осталась бы
 * без своей единственной законной перезагрузки.
 *
 * Тридцать секунд удовлетворяют обоим условиям с большим запасом с обеих
 * сторон. Это инженерное число, а не размер из макета: оно ничего не рисует.
 */
const COOLDOWN_MS = 30_000

/** Когда вкладка перезагружалась в прошлый раз. `null` — не перезагружалась. */
function lastReloadAt(): number | null {
  const raw = window.sessionStorage.getItem(KEY)
  if (raw === null) return null
  const at = Number(raw)
  return Number.isFinite(at) ? at : null
}

/** Признак именно этой беды: браузер не смог забрать кусок кода. */
function isStaleChunk(error: Error): boolean {
  const text = `${error.name} ${error.message}`
  return (
    /dynamically imported module/i.test(text) ||
    /Importing a module script failed/i.test(text) ||
    /ChunkLoadError/i.test(text)
  )
}

/**
 * Может ли перезагрузка ещё чем-то помочь. Вопрос без последствий: только
 * читает отметку и ничего не меняет.
 *
 * Отделён от самой перезагрузки, потому что ответ нужен ЭКРАНУ, и нужен
 * во время отрисовки: кадр обязан сразу сказать правду — «обновляем» или
 * «не открылось», — а не пообещать обновление и потом передумать.
 */
function reloadWouldHelp(): boolean {
  /*
    В РАЗРАБОТКЕ ПЕРЕЗАГРУЖАЕТ VITE, А НЕ МЫ.

    Беда, ради которой этот файл написан, бывает только у выложенной
    демонстрации: имена кусков меняются выкладкой, и старого файла на хостинге
    физически не остаётся. На dev-сервере выкладок нет вовсе. Сорванная
    подгрузка там означает другое — сервер перебирает зависимости или
    перезапускается, — и Vite на это отвечает своей перезагрузкой страницы сам.

    Наша перезагрузка поверх его перезагрузки не складывается в одну, а мешает:
    вкладка возвращается на сервер ровно в ту секунду, когда он ещё не готов
    отдать кусок, снова получает отказ и снова уходит на круг. Именно так
    перепись мобильного кабинета получила экран, на котором за восемь секунд
    не появилось ни одного узла.

    Это не выключение защиты, а её место жительства: она включена там,
    где существует беда, которую она лечит.
  */
  if (import.meta.env.DEV) return false

  const at = lastReloadAt()
  return at === null || Date.now() - at >= COOLDOWN_MS
}

/**
 * Перезагрузиться, если это ещё может помочь. Возвращает, случилось ли это.
 *
 * Отказ — не поломка, а второй исход по замыслу: он означает «перезагрузка
 * уже была и не помогла». Тот, кто вызывает, обязан на него отреагировать
 * текстом на экране, а не молчанием, — иначе человек смотрит на страницу,
 * которая обещала обновиться и не обновилась.
 */
function reloadOnce(): boolean {
  if (!reloadWouldHelp()) return false

  window.sessionStorage.setItem(KEY, String(Date.now()))
  window.location.reload()
  return true
}

/**
 * Убрать отметку, которая уже истекла.
 *
 * Вызывается при старте приложения. Раньше здесь стояло безусловное удаление
 * с объяснением «приложение дошло до запуска — значит куски на месте», и это
 * рассуждение было неверным: запустился входной кусок, а куски экранов ещё
 * никто не просил. Безусловное удаление и превращало «ровно один раз»
 * в «каждый раз» — см. историю в шапке файла.
 *
 * Само по себе удаление теперь не нужно: отметка истекает по времени. Оно
 * осталось уборкой — чтобы в хранилище вкладки не лежало вечное значение,
 * о котором никто не помнит, — и трогает только то, что уже никого
 * ни от чего не удерживает.
 */
function clearChunkReloadMark(): void {
  const at = lastReloadAt()
  if (at === null) return
  if (Date.now() - at < COOLDOWN_MS) return
  window.sessionStorage.removeItem(KEY)
}

export { clearChunkReloadMark, isStaleChunk, reloadOnce, reloadWouldHelp }
