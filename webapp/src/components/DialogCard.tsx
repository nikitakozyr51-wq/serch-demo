import type { ReactNode } from "react"

import { cn } from "@/lib/utils"

/**
 * Каркас диалога (`JHW4q`): 520 или 640, поля 24, радиус 16,
 * белая заливка, кнопки внизу справа.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Лежит среди примитивов, а не внутри раздела, и это не переезд ради порядка.
 * Рамку диалога берут три разных раздела: кабинет (карта клавиш), агентство
 * (реквизиты, роль, удаление) и выдача (рядом с адресом). Пока она жила
 * в кабинете, выдача тянула её оттуда — и получалась петля: кабинет уже
 * зависит от выдачи. Проверка границ поймала это сразу, до первого запуска.
 *
 * Рамка ничего не знает ни о деньгах, ни о поиске: 520 или 640, поля 24,
 * радиус 16, ряд кнопок снизу. Это геометрия, а не правило продукта.
 */
function DialogCard({
  wide = false,
  rhythm = "tight",
  children,
}: {
  wide?: boolean
  /** 16 у диалогов-подтверждений, 20 у диалогов с выбором, 24 у формы поиска. */
  rhythm?: "tight" | "medium" | "loose"
  children: ReactNode
}) {
  return (
    <div
      role="dialog"
      aria-modal="false"
      data-slot="dialog-card"
      className={cn(
        "flex shrink-0 flex-col rounded-2xl bg-surface p-6",
        wide ? "w-160" : "w-130",
        rhythm === "tight" ? "gap-4" : rhythm === "medium" ? "gap-5" : "gap-6",
      )}
    >
      {children}
    </div>
  )
}


export { DialogCard }
