import { Typography } from "@/components/typography"
import { cn } from "@/lib/utils"

/**
 * Чип состояния: точка 6 и слово 12/500.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ОДНА ФИГУРА НА ВЕСЬ ПРОДУКТ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Снято с компонента `xUogw` «C Чип состояния»: высота 24, зазор 6,
 * точка 6 × 6, слово 12/500. Ни заливки, ни рамки, ни радиуса.
 *
 * Заведён отдельным контролом, а не оставлен внутри строки выдачи, потому
 * что состояние в продукте показывается в трёх разных местах и до сих пор
 * показывалось тремя разными способами:
 *
 *   выдача        плашка с заливкой и рамкой, похожая на кнопку
 *   уведомления   слово «включено», повторённое трижды в подписях
 *   отказы        три исхода одинаковым серым 12-м кеглем
 *
 * Из трёх мест ни одно не помогало: плашка звала нажать, «включено» съедало
 * 29 % слов экрана, а три неразличимых серых строки означали «удалим к дате»,
 * «идёт удаление» и «исполнено» — то есть будущее, настоящее и прошлое одним
 * цветом. Точка отвечает на всё это одним взглядом.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ЦВЕТ ТОЧКИ И ЦВЕТ СЛОВА — РАЗНЫЕ СТУПЕНИ, И ЭТО НЕ НЕБРЕЖНОСТЬ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Точка идёт глифовым тоном, слово — текстовым. Фигура 6 × 6 и текст 12 px
 * одного цвета читаются разной насыщенности: мелкая заливка кажется бледнее
 * буквы. В палитре проекта для этого и заведены две ступени — `ok-glyph`
 * против `ok-text`, `warn-glyph` против `warn-text`.
 *
 * У тревожного состояния слово остаётся `text-2`, а красной становится
 * только точка: красное слово рядом с красной точкой кричит вдвое, а чип
 * сообщает факт, а не поднимает тревогу.
 */
type StateTone = "neutral" | "ok" | "warn" | "danger" | "quiet"

const DOT: Record<StateTone, string> = {
  neutral: "bg-text-3",
  ok: "bg-ok-glyph",
  warn: "bg-warn-glyph",
  danger: "bg-err-text",
  quiet: "bg-text-3",
}

const WORD = {
  neutral: "secondary",
  ok: "ok",
  warn: "warn",
  danger: "secondary",
  quiet: "dense",
} as const satisfies Record<StateTone, string>

type StateChipProps = {
  tone: StateTone
  children: string
  /**
   * Как чип называется в разметке. По умолчанию `state-chip`.
   *
   * Строка выдачи зовёт себя `status-chip` — на это имя нацелены обучение
   * и перепись нажимаемых узлов. Переименовать его значило бы молча
   * погасить шаг обучения: селектор перестал бы находиться, и вместо
   * подсветки человек увидел бы серый экран. Ровно эта беда уже была.
   */
  slot?: string
  /** Машиночитаемое состояние: по нему проверки отличают одно от другого. */
  state?: string
  /**
   * Телефонный размер: 32 вместо 24.
   *
   * Меняется только высота коробки — точка и кегль те же. На телефоне выше
   * не сам чип, а строка, в которой он стоит.
   */
  tall?: boolean
}

function StateChip({
  tone,
  children,
  slot = "state-chip",
  state,
  tall = false,
}: StateChipProps) {
  return (
    <span
      data-slot={slot}
      data-status={state}
      data-tone={tone}
      className={cn(
        // 24 в обеих плотностях: это пол по WCAG 2.5.8, уменьшать некуда.
        // Полей нет — без заливки отступать не от чего.
        "inline-flex shrink-0 items-center gap-1.5",
        tall ? "h-8" : "h-6",
      )}
    >
      <span aria-hidden className={cn("size-1.5 shrink-0 rounded-full", DOT[tone])} />
      <Typography variant="metaText" tone={WORD[tone]}>
        {children}
      </Typography>
    </span>
  )
}

export { StateChip }
export type { StateChipProps, StateTone }
