import { expect, test } from '@playwright/test'
import { seedSession } from '../lib/session'

/**
 * Строка выдачи держит нарисованную высоту, а список прокручивается.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ ОТДЕЛЬНЫЙ СЛОЙ, ЕСЛИ ЕСТЬ ПРОВЕРКА ТОКЕНОВ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Токен `--row-obj` всё это время считался ВЕРНО: 88 в просторном, 64
 * в плотном. Проверка токенов сравнивала переменную с макетом и была
 * зелёной. А на экране строка стояла 55.
 *
 * Разница в том, что строка — элемент колоночного flex-списка. Высота,
 * заданная классом, для такого элемента не обязательство, а пожелание:
 * когда пятьдесят три строки по 88 не помещаются в 836 доступных
 * пикселей, браузер сжимает каждую до min-content. Воздух над адресом
 * и под мета-строкой исчезает, текст упирается в делитель соседней
 * строки — это и есть «текст выходит из блока», о котором говорил
 * владелец. Величина при этом верна везде, кроме экрана.
 *
 * Отсюда правило слоя: **мерить отрисованный прямоугольник, а не токен.**
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ВТОРАЯ ПОЛОВИНА: ПОТЕРЯННЫЕ СТРОКИ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * У той же ошибки есть последствие дороже кривой высоты. Список стоял
 * с `overflow: hidden`, и после того, как строки перестали сжиматься,
 * тридцать восемь объектов из пятидесяти трёх оказались бы недоступны
 * ничем — ни колесом, ни клавишей. Обрезка без прокрутки — это не
 * оформление, это потеря данных.
 *
 * Поэтому слой проверяет обе половины сразу: высоту строки и то, что
 * список умеет прокручиваться до последней.
 */

/**
 * Нарисованная высота строки объекта: 96 в просторном, 64 в плотном.
 *
 * Просторная выросла с 88 до 96 сверкой 10.08.2026: сторона снимка выводится
 * из текстового блока, а не из строки, — 60 текста даёт квадрат 48 и по 24
 * воздуха, то есть ровно 96. Замер по 166 экземплярам `jsW77`.
 *
 * Имя кадра тогда отстало от содержимого — «просторно, 88» при 166
 * экземплярах по 96 внутри, — и переименовано вместе с этой правкой.
 * Разошедшееся имя опаснее разошедшегося числа: число ловит проверка,
 * а имя читает человек и верит ему.
 */
const ROW_HEIGHT = { spacious: 96, compact: 64 } as const

test('строка выдачи не сжимается, а список прокручивается до последней', async ({ page }) => {
  await seedSession(page)

  const failures: string[] = []

  for (const density of ['spacious', 'compact'] as const) {
    // Плотность сажается в хранилище ДО загрузки, а не атрибутом после.
    // Атрибут на корне живёт ровно до первой отрисовки: `useDensity`
    // читает сохранённый выбор человека и возвращает свой. Проверка,
    // ставящая атрибут после `goto`, меряет просторный режим, считая,
    // что меряет плотный, — и молчит обо всём, что ломается только
    // в плотном.
    await page.addInitScript((value) => {
      localStorage.setItem('serch.density', value)
    }, density)

    // Настоящий адрес продукта, а не стенд `/screen/search`. На стенде
    // девять замеренных строк, и они помещаются в панель целиком —
    // потерю тридцати восьми объектов там увидеть нечем.
    await page.goto('/search')
    await page.waitForSelector('[data-slot="listing-row"]')

    const measured = await page.evaluate(() => {
      const rows = [...document.querySelectorAll('[data-slot="listing-row"]')]
      const list = rows[0]?.parentElement ?? null
      return {
        count: rows.length,
        heights: rows.map((row) => Math.round(row.getBoundingClientRect().height)),
        client: list?.clientHeight ?? 0,
        scroll: list?.scrollHeight ?? 0,
        overflowY: list === null ? '' : getComputedStyle(list).overflowY,
      }
    })

    const expected = ROW_HEIGHT[density]
    const wrong = measured.heights.filter((height) => height !== expected)
    if (wrong.length > 0) {
      failures.push(
        `${density}: ${wrong.length} строк из ${measured.count} стоят не ${expected} px, ` +
          `а ${[...new Set(wrong)].join('/')}`,
      )
    }

    // Список выше окна обязан прокручиваться. Если он помещается целиком,
    // прокрутка не нужна — и требовать её было бы придиркой.
    if (measured.scroll > measured.client && !['auto', 'scroll'].includes(measured.overflowY)) {
      failures.push(
        `${density}: список ${measured.scroll} px в окне ${measured.client} px, ` +
          `а прокрутки нет (overflow-y: ${measured.overflowY}) — ` +
          `${measured.count} объектов недостижимы`,
      )
    }
  }

  expect(failures, failures.join('\n')).toEqual([])
})
