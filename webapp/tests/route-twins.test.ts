import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, test } from 'bun:test'

/**
 * У каждого адреса из пары «компьютер — телефон» есть маршрут.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ПОЧЕМУ ЭТА ПРОВЕРКА ПОЯВИЛАСЬ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Дважды случилось одно и то же, и оба раза это не увидел ни один человек.
 *
 * `/m/call` — экран прозвона на телефоне был собран, пара объявлена, маршрута
 * не было. Прозвон с телефона физически не открывался.
 *
 * `/m/search` — то же самое с выдачей. Человек, открывший поиск с телефона,
 * попадал на адрес, которого нет. Это ГЛАВНЫЙ экран продукта.
 *
 * Поломка невидима по устройству: `usePlatformRoute` честно переадресует
 * на объявленный адрес, а маршрутизатор честно отвечает «не найдено». Оба
 * правы по отдельности, и никто не отвечает за то, что они не сошлись.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ПОЧЕМУ ЧТЕНИЕМ ФАЙЛОВ, А НЕ ЗАПУСКОМ ПРИЛОЖЕНИЯ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Перепись кабинета (`cabinet:check`) обходит адреса из СВОЕГО списка,
 * и оба раза этот список был выписан рукой — то есть повторял ту же ошибку,
 * что и маршруты. Проверка, которая берёт список у того же человека, что
 * и код, не проверяет ничего.
 *
 * Здесь оба списка читаются из исходников, и сравниваются друг с другом.
 * Соврать может только тот, кто одновременно правит и пару, и маршрут —
 * а это уже осознанное решение, а не недосмотр.
 */

const here = dirname(fileURLToPath(import.meta.url))
const src = resolve(here, '../src')

const platform = readFileSync(resolve(src, 'features/cabinet/platform.ts'), 'utf8')
const routes = readFileSync(resolve(src, 'routes.tsx'), 'utf8')

/** Пары «десктопный адрес — мобильный адрес» из `TWINS`. */
const pairs = [...platform.matchAll(/\["(\/[^"]*)",\s*"(\/[^"]*)"\]/g)].map(
  ([, desktop, mobile]) => ({ desktop: desktop!, mobile: mobile! }),
)

/**
 * Адреса, у которых есть маршрут.
 *
 * Способов объявления три, и все надо учесть: короткий `productRoute('/…')`,
 * его брат `cabinetRoute('/…')` для экранов под общей рамкой кабинета
 * и полный `createRoute({ path: '/…' })`. Пропустить один значит получить
 * ложную тревогу на ровном месте — и приучить не верить проверке.
 *
 * Ровно это и случилось: проверка знала два способа из трёх и объявила
 * ненайденными двадцать пять кабинетных адресов, каждый из которых
 * прекрасно открывается. Поэтому список помощников собирается регуляркой
 * по имени, а не перечисляется: четвёртый помощник попадёт в неё сам.
 */
const declared = new Set([
  ...[...routes.matchAll(/\b\w*[Rr]oute\('([^']+)'/g)].map(([, path]) => path!),
  ...[...routes.matchAll(/path:\s*'([^']+)'/g)].map(([, path]) => path!),
])

describe('пары экранов', () => {
  test('пары вообще нашлись', () => {
    // Если разбор сломается, все проверки ниже станут зелёными на пустом
    // списке. Это самый тихий способ потерять проверку, и он закрыт здесь.
    expect(pairs.length, 'разбор TWINS не нашёл ни одной пары').toBeGreaterThan(20)
  })

  test('у каждого адреса пары есть маршрут', () => {
    const missing = pairs
      .flatMap(({ desktop, mobile }) => [desktop, mobile])
      .filter((path) => !declared.has(path))

    expect(
      [...new Set(missing)],
      'адрес объявлен парой, но маршрута нет: переход по устройству ведёт в «страница не найдена»',
    ).toEqual([])
  })

  test('мобильный адрес не ведёт сам на себя', () => {
    // Пара `["/m/x", "/m/x"]` даёт вечную переадресацию: экран отправляет
    // на себя же, и браузер уходит в цикл. Опечатка на один символ.
    const looped = pairs.filter(({ desktop, mobile }) => desktop === mobile)
    expect(looped, 'пара ведёт сама на себя — это вечная переадресация').toEqual([])
  })
})
