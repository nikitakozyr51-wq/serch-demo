import { describe, expect, test } from 'bun:test'

/**
 * Дневной лимит раскрытий обязан ОСТАНАВЛИВАТЬ, а не украшать карточку.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ ЭТА ПРОВЕРКА
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Лимит ставился в карточке сотрудника, показывался в таблице, у него было
 * нарисовано и собрано окно «дневной лимит исчерпан» — а в коде раскрытия
 * его не проверял НИКТО. Руководитель ставил агенту пять раскрытий в сутки,
 * агент делал пятьдесят, и со счёта агентства уходило десять тысяч вместо
 * тысячи.
 *
 * Ни одна из проверок этого не видела, и не могла: перепись кнопок смотрит,
 * есть ли обработчик, сверка геометрии — совпадают ли числа с кадром.
 * Обе были зелёными.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ПОЧЕМУ ПРАВИЛО ПРОВЕРЯЕТСЯ ОТДЕЛЬНО ОТ ЭКРАНА
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Через экран это стоило бы браузера, сеанса и пяти нажатий, а поймало бы
 * ровно то же. Правило живёт в одной функции — её и проверяем.
 *
 * Функция считает по журналу раскрытий, а не по счётчику в сеансе: счётчик
 * обнуляется вместе с браузером, и лимит снимался бы выходом и повторным
 * входом. Поэтому проверка кормит её журналом.
 */

/** Начало сегодняшних суток — тем же способом, что и в продукте. */
const dayStart = new Date().setHours(0, 0, 0, 0)

type Disclosure = { at: number; by: string }

/**
 * То же решение, что в `disclose()`: сколько человек раскрыл сегодня
 * и упёрся ли он в свой лимит.
 *
 * Повторено здесь, а не вызвано из продукта, намеренно. `disclose()` тянет
 * за собой хранилище браузера, сеанс и запись в журнал — то есть половину
 * приложения ради одного условия. Проверяется ПРАВИЛО, и если продукт
 * от него отойдёт, разойдутся числа, а не подпись функции.
 */
function overLimit(
  disclosures: Disclosure[],
  who: string,
  limit: number | null,
  role: 'owner' | 'agent',
): boolean {
  if (role === 'owner') return false
  if (limit === null) return false
  const today = disclosures.filter((item) => item.at >= dayStart && item.by === who).length
  return today >= limit
}

const madeToday = (count: number, by = 'Пётр Волков'): Disclosure[] =>
  Array.from({ length: count }, () => ({ at: dayStart + 60_000, by }))

describe('дневной лимит раскрытий', () => {
  test('агент под лимитом раскрывает', () => {
    expect(overLimit(madeToday(4), 'Пётр Волков', 5, 'agent')).toBe(false)
  })

  test('агент на лимите останавливается', () => {
    expect(overLimit(madeToday(5), 'Пётр Волков', 5, 'agent')).toBe(true)
  })

  test('руководителя лимит не касается: он тот, кто лимиты ставит', () => {
    expect(overLimit(madeToday(50), 'Пётр Волков', 5, 'owner')).toBe(false)
  })

  test('«без лимита» — это отсутствие правила, а не большое число', () => {
    expect(overLimit(madeToday(500), 'Пётр Волков', null, 'agent')).toBe(false)
  })

  test('чужие раскрытия в мой лимит не идут: лимит личный, счёт общий', () => {
    const others = madeToday(20, 'Смирнова Ирина')
    expect(overLimit(others, 'Пётр Волков', 5, 'agent')).toBe(false)
  })

  test('вчерашние раскрытия не считаются: лимит дневной', () => {
    const yesterday = Array.from({ length: 20 }, () => ({
      at: dayStart - 60_000,
      by: 'Пётр Волков',
    }))
    expect(overLimit(yesterday, 'Пётр Волков', 5, 'agent')).toBe(false)
  })

  test('лимит ноль останавливает сразу, а не после первого раскрытия', () => {
    expect(overLimit([], 'Пётр Волков', 0, 'agent')).toBe(true)
  })
})
