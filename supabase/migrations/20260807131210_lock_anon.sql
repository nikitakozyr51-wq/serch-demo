-- Гость не имеет доступа к журналам — прямо, а не по умолчанию.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- ЧТО НАШЛОСЬ
-- ═══════════════════════════════════════════════════════════════════════════
--
-- Первая миграция выдавала права только тем, кому они нужны, и на этом
-- считала вопрос закрытым: «этих грантов у `anon` нет вовсе». На локальной
-- базе так и было.
--
-- **В облаке оказалось иначе.** Supabase заводит проект с правилом по
-- умолчанию: любая новая таблица в схеме `public` получает права для ролей
-- `anon` и `authenticated` автоматически. То есть у гостя было право
-- обратиться к журналу раскрытий, к сотрудникам и к деньгам.
--
-- Данные при этом не утекали: правила отбора строк (RLS) для гостя не
-- написаны, и он получал пустой ответ. Проверка `access-rules` это
-- подтверждала — и подтверждала честно.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- ПОЧЕМУ ЭТОГО НЕДОСТАТОЧНО
-- ═══════════════════════════════════════════════════════════════════════════
--
-- Защита держалась на одном слое вместо двух. Достаточно одной ошибки
-- в одном правиле отбора — и открывается вся таблица, потому что право
-- обратиться к ней у гостя уже есть.
--
-- Два слоя ведут себя иначе: чтобы что-то открылось, ошибиться надо дважды
-- и в разных местах. Именно так уже сделан стоп-лист, и по той же причине.
--
-- И отдельно: код обязан делать то, что написано в его же комментарии.
-- Расхождение между «прав нет вовсе» и «права есть, но строк не видно» —
-- это не придирка. Через месяц по такому комментарию примут решение.

revoke all on public.agencies from anon;
revoke all on public.people from anon;
revoke all on public.disclosures from anon;
revoke all on public.calls from anon;
revoke all on public.saved_searches from anon;
revoke all on public.top_ups from anon;
revoke all on public.refunds from anon;
revoke all on public.stop_list from anon;

-- Подборка и её состав — единственное, что гость видит, и только на чтение.
-- Права переназначаются после отзыва: `revoke all` выше их не касается,
-- но пусть намерение стоит рядом, а не в другом файле.
revoke all on public.collections from anon;
revoke all on public.collection_items from anon;
grant select on public.collections to anon;
grant select on public.collection_items to anon;

-- Чтобы правило по умолчанию не выдало права следующей таблице, которую
-- заведут завтра. Без этой строки история повторится на первой же новой
-- таблице, и заметит её опять не человек, а проверка — если повезёт.
alter default privileges in schema public revoke all on tables from anon;
