/**
 * «Создать агентство» и «Получить доступ» ведут в кабинет.
 *
 * Кабинет — отдельное приложение (`webapp`) со своим маршрутизатором, а не
 * страница сайта. Раньше здесь стоял `/registraciya` — адрес, которого на
 * сайте нет и не будет, — и поэтому в 404 вели все кнопки призыва разом:
 * в шапке, в подвале, в герое главной, в трёх плашках прайса и в финальном
 * призыве каждой страницы. Одна строка ломала весь сайт.
 *
 * Адрес кабинета берётся из `PUBLIC_WEBAPP_URL`. Без переменной в разработке
 * подставляется `http://localhost:5173` — порт, на котором кабинет
 * поднимается по умолчанию: кнопка обязана нажиматься сразу после
 * `bun run dev`, без настройки окружения.
 *
 * В сборке без переменной адреса кабинета не существует вовсе. Вести человека
 * на несуществующий домен хуже, чем оставить его на сайте, поэтому кнопка
 * ведёт на тарифы — единственную страницу, где то же самое действие объяснено
 * ценой и повторено. Это заметный сигнал «окружение не настроено», а не тихая
 * поломка.
 */
const webappOrigin =
  import.meta.env.PUBLIC_WEBAPP_URL ?? (import.meta.env.DEV ? 'http://localhost:5173' : '')

/**
 * Кабинет в общей сборке живёт папкой `/app` того же адреса.
 *
 * Это и есть «одна ссылка»: человек открывает лендинг, жмёт «Создать
 * агентство» и оказывается в кабинете, не меняя домена. Отдельный
 * `PUBLIC_WEBAPP_URL` остаётся для случая, когда кабинет поднят своим
 * сервером — в разработке он именно так и работает.
 *
 * `BASE_URL` подставляет Astro: на своём домене это `/`, на GitHub Pages —
 * `/serch-demo/`. Двойного слэша не будет: хвост срезается.
 */
const bundledCabinet = `${BASE}/app`

export const signupHref: string = webappOrigin
  ? `${webappOrigin.replace(/\/+$/, '')}/register`
  : `${bundledCabinet}/register`

/** «Войти» из шапки сайта ведёт туда же, где живёт вход кабинета. */
export const loginHref: string = webappOrigin
  ? `${webappOrigin.replace(/\/+$/, '')}/login`
  : `${bundledCabinet}/login`

/**
 * Нормализованный путь: без завершающего слэша, кроме самой главной.
 *
 * Dev-сервер Astro отдаёт `/pricing`, а статическая сборка на хостинге —
 * `/pricing/`. Без нормализации пункт меню подсвечивался бы в одном режиме и
 * молчал в другом, причём именно в том, который видит владелец.
 */
function normalizePath(pathname: string): string {
  const trimmed = pathname.replace(/\/+$/, '')
  return trimmed === '' ? '/' : trimmed
}

/**
 * Стоит ли человек сейчас на этой странице.
 *
 * Раздел считается своим и для вложенных страниц: на статье блога подсвечен
 * «Блог». Главная сравнивается строго — иначе она была бы активна везде.
 * Внешние адреса и `mailto:` активными не бывают никогда.
 */
export function isActiveRoute(pathname: string, href: string): boolean {
  if (!href.startsWith('/')) return false

  const current = normalizePath(pathname)
  const target = normalizePath(href)

  if (target === '/') return current === '/'

  return current === target || current.startsWith(`${target}/`)
}
