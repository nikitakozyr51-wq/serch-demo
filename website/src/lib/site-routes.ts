/**
 * Адреса страниц сайта.
 *
 * В Pencil-файле адресов нет на самих кадрах, — но они есть на доске
 * `СИСТЕМА · Индексация и метаданные` (`p4AyXa`), и это источник истины по
 * адресам: там перечислены четырнадцать открытых страниц и девять закрытых,
 * у каждой свой путь. Слаги заведены здесь и в одном месте: шапка и подвал
 * ссылаются на одни и те же страницы, и разъехаться они не должны.
 */
// Часть собранных страниц стоит на транслитных адресах (`/o-kompanii`,
// `/kontakty`, `/oferta`, `/politika`, `/soglasie`, `/udalit-dannye`,
// `/dannye-udaleny`, `/podtverdite-nomer`, `/how-it-works`, `/law`), а доска
// индексации называет их `/about`, `/contacts`, `/offer`, `/policy`,
// `/consent`, `/data/delete`, `/data/deleted`, `/stop/confirm`, `/how`,
// `/legal`. Это расхождение сайта с файлом, оно названо здесь вслух и не
// закрыто: переименование десяти адресов ломает внешние ссылки и требует
// перенаправлений, то есть это отдельное решение владельца, а не побочный
// эффект починки навигации. Новые страницы заведены сразу по доске.
/**
 * Корень сайта на хостинге.
 *
 * На своём домене он пустой. На страницах проекта GitHub корень равен имени
 * репозитория: `nikitakozyr51-wq.github.io/serch-demo/`. Приписывается ко всем
 * адресам **в одном месте** — иначе часть ссылок уехала бы на корень домена
 * и отдала бы чужую страницу, причём заметить это можно только на хостинге.
 */
const BASE = import.meta.env.BASE_URL.replace(/\/+$/, '')

const withBase = (path: string): string => (path === '/' ? `${BASE}/` : `${BASE}${path}`)

const routes = {
  home: '/',
  howItWorks: '/how-it-works',
  pricing: '/pricing',
  blog: '/blog',
  about: '/o-kompanii',
  contacts: '/kontakty',
  legal: '/law',
  status: '/status',
  offer: '/oferta',
  privacy: '/politika',
  consent: '/soglasie',
  /**
   * Страницы собственника. Сюда попадают не по меню, а по ссылке из SMS или
   * письма, поэтому в шапке и подвале их нет — но адреса нужны в одном месте
   * со всеми остальными, иначе они разойдутся при первой же правке.
   *
   * `stop` в файле напечатан прямо в тексте — «на serch.ru/stop номер
   * исключается за минуту», — поэтому адрес взят буквально, а не транслитом:
   * собственник вводит его руками с бумажки. Доска индексации даёт тот же
   * `/stop`.
   */
  stop: '/stop',
  deleteData: '/udalit-dannye',
  dataDeleted: '/dannye-udaleny',
  confirmPhone: '/podtverdite-nomer',
  /**
   * Страница технических работ. Адрес не выдуман: доска индексации называет
   * её `serch.ru/maintenance` в одной строке с `serch.ru/404`. Ссылок на неё
   * нет ни в шапке, ни в подвале — её подставляет хостинг вместо всего сайта
   * на время работ, — но адрес обязан быть в одном списке с остальными.
   */
  maintenance: '/maintenance',
} as const

/**
 * Те же адреса, но с корнем хостинга.
 *
 * Страницы и компоненты берут адреса только отсюда. Канонический список выше
 * остаётся без корня: по нему сверяется имя файла страницы, а файл лежит
 * в `src/pages/pricing.astro` независимо от того, куда сайт потом положат.
 */
export const siteRoutes = Object.fromEntries(
  Object.entries(routes).map(([key, path]) => [key, withBase(path)]),
) as { [K in keyof typeof routes]: string }

