import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { test } from 'node:test'

/**
 * Состав мобильных страниц против кадров Pencil.
 *
 * **Слой ловит то, чего не ловит ни одна числовая проверка: пропущенное.**
 * Лестницы, токены и геометрия сверяют то, что построено, и молчат о том,
 * что забыли построить. Именно так со страниц пропали четырнадцать абзацев
 * «Как это устроено», пара цен на «Законе» и в блоге, надзаголовок разбора
 * и закрывающая строка подтверждения номера — всё это лежало в файле
 * и не лежало в вёрстке, а сборка была зелёная.
 *
 * Проверка простая: каждая строка мобильного кадра обязана встретиться
 * в собранном HTML соответствующей страницы. Видимость не проверяется —
 * за неё отвечает вёрстка и глаз; проверяется наличие.
 *
 * Заготовка `fixtures/mobile-frames.json` снята из Pencil обходом кадров 390
 * и содержит все текстовые узлы, кроме выключенных и кроме служебной сетки.
 * Когда меняется файл — заготовка снимается заново, а не правится руками.
 *
 * **Про мобильный текст важное:** на 390 файл не переносит десктопный абзац,
 * а переписывает его короче. «от момента, когда его опубликовали на площадке»
 * становится «от публикации на площадке». Поэтому у страницы бывают две
 * редакции одного абзаца, и лишняя скрыта `display: none`.
 */

type Frame = { path: string; node: string; texts: string[] }

const frames: Frame[] = JSON.parse(
  await readFile(new URL('./fixtures/mobile-frames.json', import.meta.url), 'utf8'),
)

/**
 * Расхождения, оставленные сознательно. Каждое — с причиной, а не «пока так».
 */
const PHONE_REASON =
  'номера в файле стоят в настоящих петербургских диапазонах 911, 921 и 981 — ' +
  'такой номер прямо сейчас может принадлежать живому человеку, а страница ' +
  'публичная. В продукте они заменены на выдуманные +7 900 000-··-··, ' +
  'см. webapp/src/lib/demo-phone.ts. Это единственное место, где вёрстка ' +
  'сознательно расходится с файлом-законом, и расходится в пользу людей, ' +
  'чьи номера в файл попали.'

const WAIVED = new Map<string, string>([
  ['+7 900 000-25-83', PHONE_REASON],
  [
    'Мы отправили код на +7 911 ··· ·· 83. Без подтверждения исключить номер нельзя: иначе скрыть чужое объявление смог бы любой.',
    PHONE_REASON,
  ],
  [
    'status.serch.ru · публичная страница',
    'файл спорит сам с собой: подпись обещает поддомен status.serch.ru, ' +
      'а адрес страницы в навигации и подвале — serch.ru/status. ' +
      'До решения владельца держим один адрес, названный верно.',
  ],
])

/** HTML-мнемоники, которыми Astro кодирует кавычки и амперсанд в тексте. */
function decode(html: string): string {
  return html
    .replace(/&#34;|&quot;/g, '"')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&amp;/g, '&')
    .replace(/&laquo;/g, '«')
    .replace(/&raquo;/g, '»')
    .replace(/&nbsp;| /g, ' ')
}

function normalise(value: string): string {
  return decode(value).replace(/\s+/g, ' ').trim()
}

/**
 * Текст страницы без разметки.
 *
 * Тег заменяется пробелом, а не пустотой: заголовок в файле разбит на строки
 * тремя `span`, и склейка без пробела дала бы «Что мы знаемо рынке» — то есть
 * проверка падала бы на верной вёрстке. Так же поступает и браузер, когда
 * отдаёт `innerText` блочных элементов.
 */
function textOf(html: string): string {
  // Подсказка поля — тоже видимый текст, но лежит она атрибутом, а не узлом.
  // Без этой строки проверка требовала бы «+7 900 000-25-83» текстом и была
  // бы права ровно наоборот: настоящее поле ввода обязано держать пример
  // в `placeholder`, иначе он не исчезнет при наборе.
  const attributes = [...html.matchAll(/(?:placeholder|value|alt|aria-label)="([^"]*)"/g)]
    .map((match) => match[1])
    .join(' ')

  return normalise(html.replace(/<[^>]+>/g, ' ') + ' ' + attributes)
}

for (const frame of frames) {
  test(`мобильный кадр ${frame.node} собран целиком: ${frame.path}`, async () => {
    const file = frame.path === '/' ? 'index.html' : `${frame.path.replace(/^\//, '')}/index.html`
    const html = textOf(await readFile(new URL(`../dist/${file}`, import.meta.url), 'utf8'))

    const missing = frame.texts
      .map(normalise)
      .filter((text) => text.length > 2)
      .filter((text) => !WAIVED.has(text))
      .filter((text) => !html.includes(text))

    assert.deepEqual(
      missing,
      [],
      `строки кадра ${frame.node} не найдены на ${frame.path}:\n  ${missing.join('\n  ')}`,
    )
  })
}
